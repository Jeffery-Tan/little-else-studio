class DraftIn(Input):
    request_id: str = Field(min_length=1, max_length=128, pattern=r'^[A-Za-z0-9_.:-]+$')
    kind: Literal['image', 'video']
    prompt: str | None = Field(min_length=1, max_length=5000)
    preserve_prompt_from: PreservedPrompt | None = None
    source_version: int = Field(ge=1, strict=True)
    source_sha256: str = Field(pattern=r'^[a-f0-9]{64}$')
    reference: Reference | None = None
    references: list[PurposeReference] = Field(default_factory=list, max_length=5)
    model: str = Field(default='', max_length=100)
    duration: int | None = Field(default=None, ge=2, le=30, strict=True)
    resolution: Literal['480P', '720P', '1080P'] | None = None
    #: Which adopted segment this input is for. Only a single-shot script can
    #: infer this on new preparation. Old unlabelled events remain readable;
    #: their projection keeps its historical derived ordinal.
    shot_id: str | None = Field(default=None, min_length=1, max_length=64)
    #: The draft this one replaces. A revision of one shot names the draft it
    #: supersedes, so the old input stays readable but stops being generated by
    #: default instead of reading as a brand-new shot.
    supersedes: str | None = Field(default=None, min_length=1, max_length=160)
    reuse_attempt_id: str | None = Field(default=None, min_length=1, max_length=160)

    @model_validator(mode='after')
    def prompt_mode(self):
        if self.preserve_prompt_from is not None:
            if self.prompt is not None or self.supersedes != self.preserve_prompt_from.draft_id:
                raise ValueError('复用原描述时须明确 prompt=null，并引用 supersedes 指向的同一准确输入。')
        elif self.prompt is None:
            raise ValueError('请填写实际出图描述；不改原描述时须提供准确的复用输入与指纹。')
        return self



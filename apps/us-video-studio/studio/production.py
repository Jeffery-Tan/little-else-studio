                existing = [draft for draft in draft_records(jobs.store, run_id).values()
                            if draft['kind'] == 'video' and draft['source_sha256'] == source.sha256
                            and draft['source_snapshot'] == baseline]
                missing = [pair for pair in pairs if not any(
                    draft['reference'] == {'name': pair[0], 'sha256': pair[1]} for draft in existing)]
                if not missing:
                    return {'status': 'existing', 'draft_ids': [next(draft['draft_id'] for draft in existing
                        if draft['reference'] == {'name': name, 'sha256': sha256}) for name, sha256 in pairs]}
                fingerprint = digest({'images': pairs, 'source': source.sha256})
                base_request_id = 'approved-images:' + fingerprint
                retry_id = (base_request_id + ':retry:' + hashlib.sha256(retry_request_id.encode()).hexdigest()[:24]
                            if retry_request_id else None)

def digest(value):
    return hashlib.sha256(json.dumps(value, ensure_ascii=False, sort_keys=True,
                                     separators=(',', ':')).encode()).hexdigest()


def done(message):
    return SimpleNamespace(stopped_because='done', text=message, rounds=1, used_tools=[])


def outcome(attempt, message):
    """How this job actually ended, read back from the attempt it wrote.

    The submit helpers record provider trouble as an attempt status rather than
    an exception, so returning ``done`` unconditionally made the job say the
    round finished while nothing had been produced. Red line 4: a job that ran
    is not a job that delivered. The attempt's own message is what the user
    gets to read, because it is the one that says whether a resubmission is
    safe.
    """
    if attempt['status'] == 'succeeded':
        return done(message)
    return SimpleNamespace(stopped_because='incomplete', rounds=1, used_tools=[],
                           text=attempt.get('message') or '本次制作没有完成，请在制作页查看状态。')


def read_image(store, run_id, name, expected_sha256):
    path = resolve(store, run_id, name)
    if not path or path.suffix.lower() not in {'.png', '.jpg', '.jpeg', '.webp'}:
        raise ValueError('请选择本项目的静态 PNG、JPEG 或 WebP 图片。')
    with path.open('rb') as file:
        raw = file.read(24 * 1024 * 1024 + 1)
    if len(raw) > 24 * 1024 * 1024 or hashlib.sha256(raw).hexdigest() != expected_sha256:
        raise ValueError('图片超过 24 MB 或内容已变化，请重新核对。')
    try:
        with warnings.catch_warnings():
            warnings.simplefilter('error', Image.DecompressionBombWarning)
            with Image.open(io.BytesIO(raw)) as image:
                mime = {'PNG': 'image/png', 'JPEG': 'image/jpeg', 'WEBP': 'image/webp'}.get(image.format)
                if not mime or getattr(image, 'n_frames', 1) != 1 or image.width * image.height > 40_000_000 or max(image.size) > 8000:
                    raise ValueError()
                image.verify()
            with Image.open(io.BytesIO(raw)) as image:
                image.load()
    except (OSError, ValueError, SyntaxError, Image.DecompressionBombError, Image.DecompressionBombWarning):
        raise ValueError('图片不完整或超出静态图片尺寸范围，未提交生成。') from None
    return raw, mime


def normalise_references(kind, reference=None, references=None):
    """Keep reference order and purpose identical from save to provider input."""
    if reference and references:
        raise ValueError('请使用 references 列表或旧 reference 字段中的一种，避免参考图用途不明确。')
    rows = [dict(row) for row in references or []]
    if reference:
        rows = [{**reference, 'purpose': 'continuity' if kind == 'video' else 'product'}]
    if len(rows) > 5:
        raise ValueError('图片最多使用 5 张参考图。')
    if len({(row['name'], row['sha256']) for row in rows}) != len(rows):
        raise ValueError('同一张参考图只列一次，并说明它在本镜的用途。')
    for row in rows:
        if row.get('design_id') is None:
            row.pop('design_id', None)
        if row.get('design_id') and row['purpose'] not in {'character', 'scene'}:
            raise ValueError('design_id 只用于人物或场景参考图。')
    if kind == 'video' and (len(rows) != 1 or rows[0]['purpose'] != 'continuity'):
        raise ValueError('视频只接受一张已获批的 continuity 连续性首帧；人物与场景参考请先用于制作首帧。')
    return rows


def draft_references(draft):
    # Projection of a legacy row is read-only. Its persisted hash is always
    # verified before this compatibility representation is added.
    if 'references' in draft:
        return [dict(row) for row in draft['references']]
    if not draft.get('reference'):
        return []
    return normalise_references(draft['kind'], draft.get('reference'))


def validate_current_continuity(store, run_id, draft, *, drafts=None, attempts=None):
    """An uploaded first frame is valid; a generated one must remain its head."""
    if draft['kind'] != 'video':
        return
    references = draft_references(draft)
    if len(references) != 1 or references[0]['purpose'] != 'continuity':
        raise ValueError('视频输入必须保留一张准确的连续性首帧，请重新保存。')
    pair = (references[0]['name'], references[0]['sha256'])
    origin_ids = [event['attempt_id'] for event in store.read_events(run_id)
                  if event.get('kind') == 'production_output'
                  and (event.get('output', {}).get('name'), event.get('output', {}).get('sha256')) == pair]
    if not origin_ids:
        return  # Ordinary uploaded images retain their explicit human approval.
    drafts = drafts if drafts is not None else draft_records(store, run_id)
    attempts = attempts if attempts is not None else attempt_records(store, run_id)
    origins = [drafts.get(attempts.get(attempt_id, {}).get('draft_id')) for attempt_id in origin_ids]
    origin = next((row for row in reversed(origins) if row and row['kind'] == 'image'), None)
    if (not origin or not origin.get('is_current')
            or origin.get('source_snapshot') != draft.get('source_snapshot')
            or origin.get('source_sha256') != draft.get('source_sha256')
            or origin.get('shot_id') != draft.get('shot_id')
            or origin.get('design_binding') != draft.get('design_binding')):
        raise ValueError('这张首帧已不属于本镜当前图片输入，请先生成并审核当前首帧，再保存视频输入。')
    latest = next((row for row in reversed(list(attempts.values()))
                   if row.get('draft_id') == origin['draft_id']), {})
    output = latest.get('output') or {}
    if (latest.get('status') != 'succeeded'
            or (output.get('name'), output.get('sha256')) != pair):
        raise ValueError('当前图片任务尚未交付这张准确首帧，请先核实原任务，再准备视频。')


def visual_labels(store, run_id, draft):
    binding = draft.get('design_binding') or {}
    version = (binding.get('material_plan') or {}).get('version')
    if not version:
        return {'characters': [], 'scene': None}
    try:
        artifact = store.read_artifact(run_id, 'material_plan', version)
    except (PipelineError, ValueError):
        # Preserve readable draft history when its bound artifact record is
        # missing. The binding validator separately exposes the blocking issue.
        return {'characters': [], 'scene': None}
    design = (artifact.structured or {}).get('visual_design') or {}
    return {'characters': [{'id': row['id'], 'label': row.get('label') or row['id']}
                           for row in design.get('characters') or []
                           if row.get('id') in binding.get('character_ids', [])],
            'scene': next(({'id': row['id'], 'label': row.get('label') or row['id']}
                           for row in design.get('scenes') or []
                           if row.get('id') == binding.get('scene_id')), None)}


def source_snapshot(store, run_id):
    """A production baseline may gain derived outputs, never new source facts.

    The filtered evidence form is shared with the pipeline fingerprint, so a
    run's own generated files cannot invalidate either the approved script or
    the baseline that continues it (CLAUDE.md red line 7). Mutations to
    originals, observations, references, scripts or decisions still invalidate.
    """
    evidence = evidence_source_snapshot(store, run_id)
    artifacts = []
    for stage in STAGES:
        item = store.latest_artifact(run_id, stage)
        if item:
            artifacts.append({'stage': stage, 'version': item.version, 'sha256': item.sha256,
                              'intact': store.verify_artifact(run_id, stage, item.version)})
    # Which channel the user decided through, and any instruction aimed at the
    # following round, are provenance rather than source facts: neither changes
    # what was adopted, so neither may invalidate a production baseline. Excluding
    # them also keeps baselines made before these fields existed valid.
    approvals = [{k: v for k, v in a.to_dict().items()
                  if k not in {'continue_after', 'source', 'continuation_note'}}
                 for stage in STAGES for a in store.list_approvals(run_id, stage)]
    return digest({'artifacts': artifacts, 'evidence': evidence,
        'brief': store.read_run(run_id).brief, 'references': reference_fingerprint(store, run_id),
        'approvals': approvals})


def draft_records(store, run_id):
    drafts = {}
    for position, event in enumerate(store.read_events(run_id), 1):
        if event.get('kind') == 'production_draft':
            draft = event['draft']
            if digest({k: v for k, v in draft.items() if k != 'draft_sha256'}) != draft['draft_sha256']:
                raise ValueError('制作方案记录无法校验，请保留原记录并检查数据。')
            drafts[draft['draft_id']] = {**draft, 'event_seq': event.get('seq', position),
                                        'review': None, 'attempts': [],
                                        'references': draft_references(draft)}
        elif event.get('kind') == 'production_review' and event.get('draft_id') in drafts:
            if event['draft_sha256'] == drafts[event['draft_id']]['draft_sha256']:
                drafts[event['draft_id']]['review'] = event['review']
    apply_shots(drafts)
    return drafts



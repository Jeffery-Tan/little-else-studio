def shot_id_for(draft_id: str) -> str:
    """A stable identity for one storyboard position.

    Derived from the draft's own stable identity, so it survives a prompt change
    (a revision names the same shot) and never depends on list position, which
    shifts the moment a shot is added.
    """
    return 'shot-' + hashlib.sha256(draft_id.encode('utf-8')).hexdigest()[:12]


def apply_shots(drafts: dict) -> None:
    """Derive shot identity, revision numbers and supersession in place.

    Two drafts that both claim the same shot under the same script are a
    revision pair whether or not the newer one said so: the later arrival wins
    the default-generation slot and the earlier one stays readable as a
    superseded input. Nothing is deleted or rewritten; this is a projection of
    the append-only record.

    An input saved before shot identity existed is the one case this cannot
    resolve, because nothing in its record says which shot it was for. It keeps
    a positional identity inside its own script baseline, which is exactly how
    it is generated today — the improvement is that it can no longer merge with
    an explicitly labelled shot.
    """
    # Journal sequence survives reloads and same-second writes. For synthetic
    # or legacy rows without seq, dictionary insertion order is journal order.
    ordered = [row for _, row in sorted(enumerate(drafts.values(), 1),
                key=lambda item: item[1].get('event_seq', item[0]))]
    # Missing grouping fields are read as '' rather than raising: a draft that
    # predates a field is still a readable record, and one incomplete row must
    # not make the whole production state unreadable.
    def group(row, shot):
        return (row.get('kind'), row.get('source_sha256'), row.get('source_snapshot'), shot)

    # Pass 1: labelled shots keep their label. Revision numbers are per shot.
    claimed: dict[tuple, int] = {}
    for draft in ordered:
        explicit = '' if draft.get('legacy_shot') else (draft.get('shot_id') or '').strip()
        if not explicit:
            draft.pop('shot_id', None)
            continue
        key = group(draft, explicit)
        draft['shot_id'] = explicit
        draft['shot_revision'] = claimed.get(key, 0) + 1
        claimed[key] = draft['shot_revision']
        draft.pop('legacy_shot', None)

    # Pass 2: unlabelled inputs take the lowest ordinal still free in their own
    # baseline, so a legacy project reads exactly as it did before.
    for draft in ordered:
        if draft.get('shot_id'):
            continue
        taken = {row['shot_id'] for row in drafts.values()
                 if row.get('kind') == draft.get('kind')
                 and row.get('source_sha256') == draft.get('source_sha256')
                 and row.get('source_snapshot') == draft.get('source_snapshot')
                 and not row.get('legacy_shot') and row.get('shot_id')}
        taken |= {row['shot_id'] for row in ordered
                  if row.get('legacy_shot') and row.get('kind') == draft.get('kind')
                  and row.get('source_sha256') == draft.get('source_sha256')
                  and row.get('source_snapshot') == draft.get('source_snapshot')
                  and row.get('shot_id')}
        index = 1
        while f'shot-{index:02d}' in taken:
            index += 1
        draft['shot_id'] = f'shot-{index:02d}'
        draft['shot_revision'] = 1
        draft['legacy_shot'] = True

    # Pass 3: an explicit supersession is honoured only when the parent really
    # is the same shot, script and media kind. A stale or unrelated draft_id in
    # that field must not retire someone else's input.
    known = {row['draft_id']: row for row in ordered}
    positions = {row['draft_id']: index for index, row in enumerate(ordered)}
    for draft in ordered:
        parent = known.get(draft.get('supersedes') or '')
        if (parent is None or parent['draft_id'] == draft['draft_id']
                or parent.get('kind') != draft.get('kind')
                or parent.get('shot_id') != draft.get('shot_id')
                or group(parent, parent.get('shot_id')) != group(draft, draft.get('shot_id'))
                or positions[parent['draft_id']] >= positions[draft['draft_id']]):
            draft['supersedes'] = None
        draft['superseded_by'] = None

    # Pass 4: without a declared successor, the latest input for a shot is the
    # one that may be generated. This is what keeps a revised prompt from
    # reading as an extra shot while the input it replaced is still ungenerated.
    for shot in {group(row, row.get('shot_id')) for row in ordered}:
        rows = [row for row in ordered if group(row, row.get('shot_id')) == shot]
        for index, row in enumerate(rows):
            row['shot_revision'] = index + 1
            if index + 1 < len(rows):
                row['superseded_by'] = rows[index + 1]['draft_id']
    for draft in ordered:
        draft['is_current'] = draft.get('superseded_by') is None


def current_draft(drafts: dict, shot_id: str, kind: str, *, baseline=None,
                  source_sha256=None) -> dict | None:
    """The one input that may be generated by default for a shot."""
    rows = [row for row in drafts.values()
            if row.get('kind') == kind and row.get('shot_id') == shot_id and row.get('is_current')
            and (baseline is None or row.get('source_snapshot') == baseline)
            and (source_sha256 is None or row.get('source_sha256') == source_sha256)]
    if not rows:
        return None
    return max(enumerate(rows, 1), key=lambda item: item[1].get('event_seq', item[0]))[1]


def target_shots(store, run_id, kind='image'):
    """Which shots this project actually asks for, and from where.

    The count comes from the adopted script, never from a hard-coded number: a
    six-segment script asks for six inputs, a three-segment one asks for three.
    A legacy prose script with no structure has no readable shot list, so the
    answer stays honestly unknown rather than guessed from the sentence.
    """
    artifact = store.latest_artifact(run_id, 'writing')
    return _artifact_target_shots(artifact, kind)


def _artifact_target_shots(artifact, kind):
    """One identity rule for both current targets and exact historical sources."""
    if not artifact:
        return {'kind': kind, 'source': 'no_script', 'shots': [], 'complete_list': False,
                'source_version': None, 'source_sha256': None,
                'notice': '还没有已保存的脚本，因此没有目标镜头清单。'}
    segments = (artifact.structured or {}).get('segments')
    if not isinstance(segments, list) or not segments:
        return {'kind': kind, 'source': 'legacy_prose', 'shots': [], 'complete_list': False,
                'source_version': artifact.version, 'source_sha256': artifact.sha256,
                'notice': '这一版脚本是纯文本稿，没有可读的镜头清单；'
                          '请按用户需求核对镜头数量，不要假定。'}
    shots = []
    for index, segment in enumerate(segments, 1):
        row = segment if isinstance(segment, dict) else {}
        picture = str(row.get('picture') or '').strip().replace('\n', ' ')
        label = f'{picture[:40]}' if picture else f'第 {index} 段'
        shots.append({'ordinal': index, 'shot_id': row.get('shot_id') or f'shot-{index:02d}',
                      **({'page_id':row['page_id']} if row.get('page_id') else {}), 'label': label,
                      'timecode': str(row.get('tc') or '')})
    return {'kind': kind, 'source': 'writing_segments', 'shots': shots, 'complete_list': True,
            'source_version': artifact.version, 'source_sha256': artifact.sha256,
            'notice': f'目标镜头来自脚本第 {artifact.version} 版的 {len(shots)} 个段落。'}


def coverage(drafts: dict, kind, *, targets=None, baseline=None):
    """Per-shot input and media readiness against the target shot list.

    This is the check that stops "one draft exists" from counting as "the whole
    storyboard is ready", and "one image exists" from counting as "the set is
    delivered". A shot with a settled failure is reported as failed, not as an
    empty slot, so the reader sees which shot needs attention.
    """
    rows = []
    for shot in (targets or {}).get('shots', []):
        draft = current_draft(drafts, shot['shot_id'], kind, baseline=baseline,
                              source_sha256=(targets or {}).get('source_sha256'))
        source_ready = bool(draft) and draft.get('source_ready', True) and (
            baseline is None or draft['source_snapshot'] == baseline)
        attempts = list(draft.get('attempts') or []) if draft else []
        settled = [a for a in attempts if a.get('status') in SETTLED_MEDIA_PHASES]
        delivered = next((a for a in reversed(settled)
                          if a.get('status') == 'succeeded' and a.get('output')
                          and a.get('output_available', True)), None)
        # Replacing a prompt cannot erase uncertainty about an earlier remote
        # request for this same shot. Preserve that original task identity.
        for previous in drafts.values():
            if (draft and previous['draft_id'] != draft['draft_id']
                    and previous.get('kind') == kind
                    and previous.get('shot_id') == shot['shot_id']
                    and previous.get('source_sha256') == draft.get('source_sha256')
                    and previous.get('source_snapshot') == draft.get('source_snapshot')):
                original = (previous.get('attempts') or [{}])[-1]
                if ATTEMPT_SHOT_STAGE.get(original.get('status')) in {
                        'submitted', 'generating', 'retrieving', 'unverified'}:
                    attempts.append(original)
        latest = attempts[-1] if attempts else {}
        phase = latest.get('status')
        if phase in UNRESOLVED_MEDIA_PHASES:
            stage = ATTEMPT_SHOT_STAGE.get(phase, 'unverified')
            blocker = 'attempt_unresolved' if stage == 'unverified' else None
            action = 'check_original_task' if blocker else 'wait_for_task'
        elif draft and not source_ready:
            stage, blocker, action = ('unprepared', 'visual_design_invalid', 'complete_visual_design') if (
                draft.get('design_issue')) else ('unprepared', 'stale_source', 'save_current_input')
        elif delivered and latest is delivered:
            stage, blocker, action = 'completed', None, 'review_result'
        elif phase in ATTEMPT_SHOT_STAGE and ATTEMPT_SHOT_STAGE[phase] in {
                'submitted', 'generating', 'retrieving'}:
            stage, blocker, action = ATTEMPT_SHOT_STAGE[phase], None, 'wait_for_task'
        elif draft and (not attempts or phase == 'not_started'):
            stage = 'awaiting_authorisation' if draft.get('awaiting_authorisation') else 'input_ready'
            blocker, action = None, 'authorise_generation'
        elif phase in ATTEMPT_SHOT_STAGE and ATTEMPT_SHOT_STAGE[phase] == 'failed':
            stage, blocker, action = 'failed', 'generation_failed', 'diagnose_attempt'
        elif draft:
            stage, blocker, action = 'unverified', 'attempt_unresolved', 'check_original_task'
        else:
            stage, blocker, action = 'unprepared', 'unprepared', 'prepare_input'
        rows.append({
            'ordinal': shot['ordinal'], 'shot_id': shot['shot_id'], 'label': shot.get('label', ''),
            'timecode': shot.get('timecode', ''),
            'draft_id': draft['draft_id'] if draft else None,
            'draft_sha256': draft.get('draft_sha256') if draft else None,
            'revision': draft.get('shot_revision') if draft else None,
            'source_ready': source_ready,
            'stage': stage, 'stage_label': SHOT_STAGE_LABELS[stage],
            'blocker': blocker, 'next_action': action,
            'retryable': bool(blocker in RETRYABLE_BLOCKERS
                              or (blocker == 'generation_failed' and draft)),
            'reason': ((latest.get('message') or ('这次提交结果尚未确认，请先核实原任务。'
                        if stage == 'unverified' else '原任务仍在处理，请等待这次任务返回。'))
                       if phase in UNRESOLVED_MEDIA_PHASES else
                       draft.get('design_issue', '') if draft and not source_ready else latest.get('message', '') or ''),
            'attempt_id': latest.get('attempt_id'),
            'attempt_status': latest.get('status'),
            'task_id': latest.get('task_id'),
            'output': (delivered or {}).get('output'),
            'superseded_draft_ids': [row['draft_id'] for row in drafts.values()
                                     if row.get('shot_id') == shot['shot_id']
                                     and row['kind'] == kind and not row.get('is_current')
                                     and (baseline is None or row.get('source_snapshot') == baseline)],
        })
    if not (targets or {}).get('complete_list'):
        return {'kind': kind, 'complete_list': False, 'shots': rows, 'ready': False,
                'delivered': False, 'unknown_targets': True,
                'pending': False, 'failed': False, 'unknown': False,
                'active': False, 'awaiting_authorisation': False, 'input_ready': False,
                'state': 'unknown_targets'}
    stages = {row['stage'] for row in rows}
    state = ('complete' if rows and stages == {'completed'} else
             'unknown' if 'unverified' in stages else
             'failed' if 'failed' in stages else
             'in_progress' if stages & {'submitted', 'generating', 'retrieving'} else
             'incomplete' if not rows or 'unprepared' in stages else
             'awaiting_authorisation' if 'awaiting_authorisation' in stages else 'input_ready')
    return {
        'kind': kind, 'complete_list': True, 'shots': rows,
        'total': len(rows),
        'ready': bool(rows) and all(row['stage'] != 'unprepared' for row in rows),
        'delivered': bool(rows) and all(row['stage'] == 'completed' for row in rows),
        'pending': any(row['stage'] in {'awaiting_authorisation', 'submitted',
                                        'generating', 'retrieving'} for row in rows),
        'failed': any(row['stage'] == 'failed' for row in rows),
        'unknown': 'unverified' in stages,
        'active': bool(stages & {'submitted', 'generating', 'retrieving'}),
        'awaiting_authorisation': 'awaiting_authorisation' in stages,
        'input_ready': bool(rows) and all(row['source_ready'] for row in rows),
        'state': state,
        'unready_shots': [row['ordinal'] for row in rows if row['stage'] == 'unprepared'],
    }


def missing_shot_summary(result: dict) -> str:
    """A short, specific sentence about which shots are not there yet."""
    shots = result.get('shots') or []
    if not shots:
        return '目标镜头清单不可读'
    if not result.get('ready'):
        return '尚未准备输入的第 ' + '、'.join(str(n) for n in result['unready_shots']) + ' 镜'
    if result.get('failed'):
        return '第 ' + '、'.join(str(row['ordinal']) for row in shots
                                if row['stage'] == 'failed') + ' 镜制作失败'
    if result.get('pending'):
        return '第 ' + '、'.join(str(row['ordinal']) for row in shots
                                if row['stage'] in {'awaiting_authorisation', 'submitted',
                                                    'generating', 'retrieving'}) + ' 镜仍在等待'
    missing = [str(row['ordinal']) for row in shots if row['stage'] != 'completed']
    return '第 ' + '、'.join(missing) + ' 镜还没有可阅读的结果'


def attempt_records(store, run_id, ledger_entries=None, *, execution_active=False):
    """Every production attempt as one row, with its ledger status.

    A module-level function because two callers need the same answer: the page,
    through ``Production.attempts``, and the controller's read-only projection,
    which has no service object. Splitting them is how the screen and the chat
    started disagreeing about whether an attempt was in flight.

    ``ledger_entries`` is ``Ledger.entries(run_id)`` when the caller has a
    ledger. Without it the usage columns stay ``not_started`` rather than being
    guessed.
    """
    items = {}
    for e in store.read_events(run_id):
        if e.get('kind') == 'production_attempt':
            items[e['attempt_id']] = {k: v for k, v in e.items() if k not in {'kind', 'seq'}}
        elif e.get('kind') == 'production_status' and e.get('attempt_id') in items:
            items[e['attempt_id']].update(e['update'])
        elif e.get('kind') == 'production_output' and e.get('attempt_id') in items:
            items[e['attempt_id']]['output'] = e['output']
    ledger = {r.call_id: r for r in (ledger_entries or [])}
    for a in items.values():
        row = ledger.get(a['attempt_id'])
        a.update(usage_status=row.usage_status if row else 'not_started',
                 usage_unit=row.usage_unit if row else None,
                 usage_quantity=row.usage_quantity if row else None,
                 estimated_cny=row.estimated_cny if row else None)
        if not execution_active:
            # A service that is not running did not leave these mid-flight; what
            # it left is an uncertain submission, and saying so is what stops the
            # next reader from resubmitting it.
            if a['status'] in {'preparing', 'submitting'}:
                a.update(status='unknown' if row else 'not_started',
                    message='本地执行已中断，提交结果待核实，没有自动重发。' if row else '本地执行在调用记录前结束，没有提交生成。')
            elif a['status'] == 'downloading':
                a.update(status='retrieve_failed', message='结果取回被中断，可查询原任务继续取回，不会重新生成。')
    return items



def image_recovery_state(run_id, attempt, draft):
    """Legal user decisions for this exact record, never a provider outcome.

    Workspace already projects output byte availability. The write boundary
    additionally reopens and validates the image under the same run lock.
    """
    output = attempt.get('output')
    identity = {key: attempt.get(key) for key in (
        'attempt_id', 'draft_id', 'media_kind', 'status', 'task_id',
        'provider_thread_id', 'provider_turn_id', 'provider_outcome',
        'failure_code', 'observed_image_calls', 'usage_status', 'usage_quantity')}
    identity.update(run_id=run_id, output=output,
                    attempt_draft_sha256=attempt.get('draft_sha256'),
                    draft_sha256=draft.get('draft_sha256'),
                    source_version=draft.get('source_version'),
                    source_sha256=draft.get('source_sha256'))
    modes = []
    reason = ''
    if (attempt.get('media_kind') == 'image'
            and attempt.get('status') in {'unknown', 'submission_unknown'}
            and not attempt.get('task_id')):
        if not output:
            modes = ['not_submitted', 'retry_with_unknown_cost']
        elif (attempt.get('output_available') is True
                and attempt.get('provider_outcome') == 'unknown'
                and attempt.get('draft_sha256') == draft.get('draft_sha256')
                and isinstance(attempt.get('draft_sha256'), str)):
            modes = ['retry_with_unknown_cost']
        else:
            reason = '已记录的保留图片暂不能核对，请先核实原文件；不能记作未提交或重新生成。'
    return {'modes': modes, 'attempt_sha256': digest(identity),
            'has_retained_output': bool(output), 'reason': reason}

def preparation_failure(exc: Exception) -> dict:
    """One shape for every refusal, so the controller never has to guess.

    ``code``, ``message``, ``target``, ``retryable``, ``next_action`` and
    ``needs_user_decision`` answer "what do I do about this", which a single
    sentence ("check the script, reference and parameters") could not give. A
    refusal nobody classified is reported as unclassified rather than silently
    upgraded to retryable — retrying a submission that may have reached the
    provider is how you pay twice.
    """
    if isinstance(exc, ProductionError):
        return exc.to_dict()
    if isinstance(exc, PipelineError):
        return {'code': getattr(exc, 'code', '') or 'pipeline', 'message': str(exc),
                'target': {}, 'retryable': False, 'next_action': 'resolve_blocker',
                'needs_user_decision': True}
    return {'code': 'unclassified', 'message': str(exc) or '制作方案未保存。', 'target': {},
            'retryable': False, 'next_action': 'review_record', 'needs_user_decision': True}


def _endpoint_host(endpoint):
    if isinstance(endpoint, str) and '//' in endpoint:
        return endpoint.split('//', 1)[1].split('/', 1)[0]
    return ''


def agent_draft_projection(draft, *, include_input=False):
    """Model-only input index; the workbench keeps the complete original."""
    keys = {
        'actor', 'created_at', 'draft_id', 'draft_sha256', 'kind', 'model',
        'duration', 'resolution', 'parameters', 'estimate', 'shot_id',
        'source_version', 'source_sha256', 'source_snapshot', 'supersedes',
        'superseded_by', 'shot_revision', 'is_current', 'design_issue',
        'design_labels', 'source_ready', 'reference_approved', 'can_generate',
        'reason', 'event_seq', 'review', 'references', 'reuse',
    }
    result = {k: deepcopy(v) for k, v in draft.items() if k in keys}
    result['attempts'] = [{k: deepcopy(v) for k, v in attempt.items() if k != 'endpoint'}
                         | ({'endpoint_host': _endpoint_host(attempt.get('endpoint'))}
                            if _endpoint_host(attempt.get('endpoint')) else {})
                         for attempt in draft.get('attempts') or []]
    reference = {k: deepcopy(v) for k, v in (draft.get('reference') or {}).items() if k != 'url'}
    result['reference'] = reference or None
    result['input_details_included'] = include_input
    result['read_input'] = {'tool': 'read_production', 'draft_id': draft['draft_id'],
                            'expected_sha256': draft['draft_sha256']}
    if include_input:
        # Both distinct source descriptions are needed, once each. Aliases and
        # the original request envelope do not add content or authority.
        for key in ('shot_prompt', 'compiled_prompt', 'design_binding',
                    'shot_binding', 'reuse_dependencies'):
            if key in draft:
                result[key] = deepcopy(draft[key])
    return result


def agent_production_state(store, pipeline, run_id, *, draft_id=None, expected_sha256=None) -> dict:
    """The controller's read-only view of production, with nothing to leak.

    Assembled from the same projection the page uses, so the controller and the
    screen cannot disagree about which shot is blocked. Three things are
    deliberately absent: the browser's approval nonce, material URLs (the
    controller has no business fetching project media) and provider response
    bodies. ``endpoint`` is reduced to its host because a signed query string
    can appear in it.
    Default reads index every input without repeating full prompts. An exact
    identity/hash reads one original in full, including stale historical input;
    that read never makes it current, approved or eligible for generation.
    """
    if (draft_id is None) != (expected_sha256 is None):
        raise ValueError('读取原制作输入须同时提供准确 draft_id 和 expected_sha256。')
    state = _read_state_without_service(store, pipeline, run_id)
    if draft_id is not None:
        matches = [draft for draft in state['drafts'] if draft['draft_id'] == draft_id
                   and draft['draft_sha256'] == expected_sha256]
        if len(matches) != 1:
            raise ValueError('这份准确制作输入未能核对，请用当前状态中的身份与指纹读取；不会换成最新输入。')
        selected = matches[0]
        # Do not resend every historical input/catalog after reading the index.
        # Global obstructions stay visible even when they belong to another shot.
        return {
            'view': 'input_detail',
            'notice': '本次只读取这一份准确输入与绑定的来源段落；完整历史清单用无参数 read_production。'
                      '来源段落是方案原文，不代表像素观察、采用或图审。历史输入仍是历史；未决提交只查询原任务，不自动重提。',
            **{key: deepcopy(state[key]) for key in ('baseline', 'targets', 'shots',
                'unresolved_attempts', 'preparation_blocker', 'open_stage_tasks')},
            'drafts': [agent_draft_projection(selected, include_input=True)],
            'source_shot': _agent_source_shot(store, run_id, selected, state),
        }
    drafts = [agent_draft_projection(draft) for draft in state['drafts']]
    return {
        'view': 'input_detail' if draft_id is not None else 'state_index',
        'notice': ('读取制作状态和保存制作输入本身不产生提供方费用；准备设计所需模型调用正常记录用量。生成、图审与费用只能由用户在'
                   '制作界面确认。已提交的提供方任务只查询原任务，绝不自动重提。'
                   '默认为完整状态索引；核对或修改原描述时，用 read_input 的准确身份与指纹读取详情，不猜最新输入。'),
        'baseline': state['baseline'],
        'targets': state['targets'],
        'shots': state['shots'],
        'unresolved_attempts': state['unresolved_attempts'],
        'sources': state['sources'],
        'materials': [{k: v for k, v in m.items() if k != 'url'} for m in state['materials']],
        'drafts': drafts,
        'video_sequence': state['video_sequence'],
        'edit_plan': state['edit_plan'],
        'assemblies': state['assemblies'],
        'latest_approved_image': state['latest_approved_image'],
        'visual_design_status': state['visual_design_status'],
        'preparation_blocker': state['preparation_blocker'],
        'open_stage_tasks': state['open_stage_tasks'],
        'design_upgrade_action': state['design_upgrade_action'],
        'reuse_candidates': state['reuse_candidates'],
    }


def _agent_source_shot(store, run_id, draft, state):
    """Read only the immutable source bound to this exact input; never latest."""
    identity = {'stage': 'writing', 'version': draft.get('source_version'),
                'sha256': draft.get('source_sha256'), 'shot_id': draft.get('shot_id')}
    unavailable = {'available': False, **identity,
                   'reason': '这份输入的准确来源或唯一段落无法核对；不替换为最新方案。'}
    sources = [row for row in state.get('sources', [])
               if row.get('version') == identity['version']
               and row.get('artifact_sha256') == identity['sha256']]
    if len(sources) != 1 or type(identity['version']) is not int or identity['version'] < 1:
        return unavailable
    artifact = store.read_artifact(run_id, 'writing', identity['version'])
    if artifact.sha256 != identity['sha256'] or not store.verify_artifact(run_id, 'writing', artifact.version):
        raise ValueError('这份输入所绑定的原方案指纹无法核对；不会读取最新方案替代。')
    if artifact.digest_algorithm != 'artifact-v2':
        return {**unavailable, 'reason': '旧方案指纹只覆盖正文，未覆盖结构化段落；不能将该段标为已核验原文。'}
    targets = _artifact_target_shots(artifact, draft.get('kind', 'image'))
    matches = [row for row in targets['shots'] if row['shot_id'] == identity['shot_id']]
    if len(matches) != 1:
        return unavailable
    target = matches[0]
    segment = (artifact.structured or {})['segments'][target['ordinal'] - 1]
    if not isinstance(segment, dict):
        return unavailable
    current = state.get('targets', {}).get(draft.get('kind', 'image'), {})
    return {'available': True, **identity, 'ordinal': target['ordinal'],
            **({'page_id': target['page_id']} if target.get('page_id') else {}),
            'is_current_source': (current.get('source_version') == artifact.version
                                  and current.get('source_sha256') == artifact.sha256),
            'segment': deepcopy(segment)}


def _read_state_without_service(store, pipeline, run_id, *, ledger=None,
                                execution_active=False):
    """``Production.state`` for a caller that has no service object.

    One definition of "what is the production state" is the point: if the
    controller re-derived it, a shot could read as blocked on screen and ready
    in chat. The turn-level deliverable check calls this on every model round, so
    it stays a small number of event-log scans and no media reads.

    The controller has no production service, but still reads the same effective
    ledger journal. Missing service state cannot make a submitted call appear
    unstarted or erase an uncertain task from the recovery projection.
    """
    events = store.read_events(run_id)
    drafts = draft_records(store, run_id)
    baseline = source_snapshot(store, run_id)
    approvals = {}
    for event in events:
        if event.get('kind') == 'production_material_approval':
            approvals[(event['name'], event['sha256'])] = event['approved']
    attempts = attempt_records(store, run_id,
                               ledger.entries(run_id) if ledger is not None else Ledger.project_entries(store, run_id),
                               execution_active=execution_active)
    materials = [{**m, 'approved': approvals.get((m['name'], m['sha256']), False)}
                 for m in evidence_snapshot(store, run_id)['materials']]
    hashes = {m['name']: m['sha256'] for m in materials}
    images = {(m['name'], m['sha256']): m for m in materials if m['kind'] == 'image'}
    latest_approved_image = next((images.get((event.get('name'), event.get('sha256')))
        for event in reversed(events)
        if event.get('kind') == 'production_material_approval' and event.get('approved')
        and approvals.get((event.get('name'), event.get('sha256')))
        and images.get((event.get('name'), event.get('sha256')))), None)
    current = store.latest_artifact(run_id, 'writing')
    # Each projection gets one fresh Pipeline memo. Every draft still checks its
    # exact binding, but the same stage/evidence state is not rebuilt per shot.
    # This memo never survives the read or reaches a later generation check.
    stage_memo = {}
    ready_source = pipeline.is_complete(run_id, 'writing', stage_memo)
    visual = design_status(store, pipeline, run_id, stage_memo=stage_memo)
    sources = []
    for artifact in store.list_artifacts(run_id, 'writing'):
        ready = visual['ready'] and current == artifact and (ready_source or
            any(d['source_sha256'] == artifact.sha256 and d['source_snapshot'] == baseline
                for d in drafts.values()))
        sources.append({'version': artifact.version, 'artifact_sha256': artifact.sha256,
                        'summary': artifact.summary, 'ready': ready})
    for draft in drafts.values():
        draft['design_issue'] = ''
        try:
            validate_visual_binding(store, pipeline, run_id, draft, stage_memo=stage_memo)
            validate_current_continuity(store, run_id, draft, drafts=drafts, attempts=attempts)
            if any(hashes.get(reference['name']) != reference['sha256']
                   for reference in draft['references']):
                raise ValueError('本镜绑定的参考图已变化或缺失，请重新核对准确图片并保存制作输入。')
        except ValueError as exc:
            draft['design_issue'] = str(exc)
        draft['design_labels'] = visual_labels(store, run_id, draft)
        draft['source_ready'] = draft['source_snapshot'] == baseline and not draft['design_issue']
        ref = draft['reference']
        draft['reference_approved'] = bool(ref and approvals.get((ref['name'], ref['sha256']))
                                           and hashes.get(ref['name']) == ref['sha256'])
        draft['attempts'] = [a for a in attempts.values() if a['draft_id'] == draft['draft_id']]
        for attempt in draft['attempts']:
            output = attempt.get('output')
            if output:
                attempt['output_available'] = bool(isinstance(output, dict)
                    and output.get('name') in hashes
                    and hashes[output['name']] == output.get('sha256'))
            if attempt.get('media_kind') == 'image':
                attempt['recovery'] = image_recovery_state(run_id, attempt, draft)
        # A replaced input is readable history, not the default thing to
        # generate. The page and the controller both filter on ``is_current``,
        # but ``can_generate`` is the explicit answer and must agree with them.
        draft['can_generate'] = not draft.get('reuse') and bool(draft.get('is_current')) and draft['source_ready'] and (
            draft['kind'] == 'image' or draft['reference_approved'])
        if draft.get('reuse'):
            draft['reason'] = '这份输入仅绑定已生成字节；如需重新生成，请准备新输入并重新核对费用。'
    result = {'sources': sources, 'materials': materials, 'drafts': list(drafts.values()),
              'baseline': baseline, 'visual_design_status': visual}
    result['targets'] = {kind: target_shots(store, run_id, kind) for kind in ('image', 'video')}
    result['reuse_candidates'] = reuse_candidates(store, pipeline, run_id, drafts=drafts, attempts=attempts,
                                                 baseline=baseline, hashes=hashes, stage_memo=stage_memo)
    result['video_sequence'] = video_sequence(result)
    current_images = [shot['image_draft_id'] for shot in result['video_sequence']]
    plans = [plan for plan in edit_plan_records(store, run_id).values()
             if plan['source_snapshot'] == baseline and plan['image_draft_ids'] == current_images]
    result['edit_plan'] = plans[-1] if plans else None
    result['assemblies'] = [event['assembly'] for event in events
                            if event.get('kind') == 'production_assembly']
    result['shots'] = {kind: coverage(drafts, kind, targets=result['targets'][kind],
                                      baseline=baseline) for kind in ('image', 'video')}
    ordinals = {kind: {row['shot_id']: row['ordinal'] for row in result['targets'][kind]['shots']}
                for kind in ('image', 'video')}
    result['unresolved_attempts'] = [{
        'kind': draft['kind'], 'shot_id': draft['shot_id'],
        'ordinal': ordinals[draft['kind']].get(draft['shot_id']),
        'draft_id': draft['draft_id'], 'attempt_id': attempt['attempt_id'],
        'status': attempt['status'], 'task_id': attempt.get('task_id'),
        'message': attempt.get('message', ''),
    } for attempt in attempts.values()
        if attempt.get('status') in UNRESOLVED_MEDIA_PHASES
        and (draft := drafts.get(attempt.get('draft_id'))) is not None]
    from .design_upgrade import available as design_upgrade_action, latest_proposal
    result['design_upgrade_action'] = design_upgrade_action(store, pipeline, run_id, stage_memo)
    proposal = latest_proposal(store, run_id)
    result['design_upgrade_proposal'] = ({'id': proposal['id'], 'sha256': proposal['sha256']}
                                         if proposal else None)
    result['open_stage_tasks'] = [{'stage': stage, 'attempt_number': state.open_attempt.number}
        for stage in STAGES if (state := pipeline.stage_state(run_id, stage, stage_memo)).open_attempt]
    result['preparation_blocker'] = _preparation_blocker(
        result, pipeline.stage_state(run_id, 'writing', stage_memo), ready_source)
    result['latest_approved_image'] = latest_approved_image
    from .delivery import photo_delivery_projection
    from .project_brief import content_format
    result['photo_delivery'] = photo_delivery_projection(
        {**result, 'run_id': run_id}, current, writing_ready=ready_source, format=content_format(events))
    return result


def _preparation_blocker(state, writing, complete):
    """Prerequisites from this read's Pipeline memo, never from draft counts."""
    def blocked(code, note, action):
        return {'code': code, 'status': 'incomplete', 'note': note,
                'next_action': {'action': action}}

    if not writing.integrity_ok:
        return blocked('script_integrity', '当前脚本无法通过版本校验，已暂停制作。请查看项目诊断并核对原文件。',
                       'integrity_check')
    if state['open_stage_tasks']:
        original = state['open_stage_tasks'][0]
        label = {'intake': '需求', 'direction': '创意方向', 'material_plan': '素材设计',
                 'writing': '脚本'}[original['stage']]
        return {'code': 'stage_task_in_progress', 'status': 'incomplete',
                'note': f'{label}还有未结束的修改任务，已暂停制作。请先在团队工作记录中核对并处理原任务，再决定下一步。',
                'next_action': {'action': 'check_stage_task', **original}}
    if not writing.latest:
        return blocked('script_missing', '还没有可用于制作的脚本。请先要求团队完成脚本，并阅读后决定采用。',
                       'request_script')
    if writing.stale:
        return blocked('script_stale', '素材或上游方案已变化，当前脚本已失效，不能继续制作。请明确要求更新受影响的方案，再采用新脚本。',
                       'request_upstream_revision')
    if not complete:
        if writing.approval and writing.approval.decision == 'returned':
            return blocked('script_returned', '当前脚本已退回，不能继续制作。请先按退回意见修改，再阅读新版脚本决定是否采用。',
                           'request_script_revision')
        if writing.can_approve:
            return blocked('script_awaiting_decision', '当前脚本尚未采用，已暂停制作。请在对话区阅读脚本，决定采用或退回。',
                           'script_decision')
        return blocked('script_not_ready', '当前脚本尚未满足制作条件，已暂停制作。请查看脚本的未完成原因，明确下一轮修改范围。',
                       'review_script')
    if not state['targets']['image']['complete_list']:
        return blocked('shot_list_missing', '当前脚本没有可核对的镜头清单，不能准备分镜。请明确要求补齐逐镜脚本，再阅读新版决定是否采用。',
                       'request_script_revision')
    if not state['visual_design_status']['ready']:
        action = state.get('design_upgrade_action')
        note = '当前方案的共同人物、场景设计或逐镜身份尚不完整，不能准备可执行的分镜输入。'
        if action:
            note += f'请打开对话区的「{action["label"]}」，核对范围与模型调用后再确认；普通“继续”不会启动设计补充。'
        else:
            note += '请明确要求修改素材设计或脚本绑定，再阅读新版脚本决定是否采用。'
        return {'code': 'visual_design_missing', 'status': 'incomplete', 'note': note,
                'next_action': action or {'action': 'request_design_revision'}}
    return None


def continuation_blocker(state, goal, *, feedback=None):
    """Actions impossible in a frozen production turn; no approval or writes.

    Preparing an input can be valid while another image is awaiting recovery or
    review. Delivering media must instead settle every original request first,
    including requests hidden behind replaced or obsolete inputs.
    """
    if goal not in {'production_input', 'production_media'}:
        return None
    pending = state['unresolved_attempts']
    if goal == 'production_media' and pending:
        original = pending[0]
        label = (f'第 {original["ordinal"]} 镜' if original.get('ordinal')
                 else original['shot_id'])
        medium = '图片' if original['kind'] == 'image' else '视频'
        note = f'{label}的原{medium}任务尚未结束或结果未核实，已暂停后续媒体制作。请打开该镜头的原任务核实结果，不要重新提交。'
        status = ('unknown' if original['status'] in {'unknown', 'submission_unknown', 'retrieve_failed'}
                  else 'in_progress')
        return {'code': 'original_media_unresolved', 'status': status, 'note': note,
                'next_action': {'action': 'check_original_task',
                    **{key: original.get(key) for key in
                       ('kind', 'shot_id', 'draft_id', 'attempt_id', 'task_id')}}}
    if state['preparation_blocker']:
        return state['preparation_blocker']
    if feedback and feedback.get('binding_issue'):
        return {'code': 'feedback_binding_invalid', 'status': 'incomplete',
                'note': '所选作品无法绑定当前镜头输入，不能执行这次修改。请重新打开当前镜头并选择准确的反馈对象。',
                'next_action': {'action': 'select_current_input', 'shot_id': feedback['shot_id']}}
    return None


def edit_plan_records(store, run_id):
    plans = {}
    for event in store.read_events(run_id):
        if event.get('kind') == 'production_edit_plan':
            plan = event['plan']
            if digest({key: value for key, value in plan.items() if key != 'plan_sha256'}) != plan['plan_sha256']:
                raise ValueError('剪辑计划记录无法校验，请保留原记录并检查数据。')
            plans[plan['request_id']] = plan
    return plans


def video_sequence(workspace):
    """Current storyboard order and the exact approved image for each clip."""
    images = [d for d in workspace['drafts'] if d['kind'] == 'image' and d['source_ready']
              and d.get('is_current', True)]
    videos = [d for d in workspace['drafts'] if d['kind'] == 'video' and d['source_ready']
              and d.get('is_current', True)]
    # Replacing shot 2 appends a journal event; it must retain storyboard
    # position 2 rather than moving to the end of the video sequence.
    order = {row['shot_id']:row['ordinal'] for row in workspace.get('targets', {}).get('image', {}).get('shots', [])}
    images.sort(key=lambda row: (0, order[row['shot_id']]) if row.get('shot_id') in order
                else (1, int(row['shot_id'][5:])) if str(row.get('shot_id', '')).startswith('shot-')
                and row['shot_id'][5:].isdigit() else (2, row.get('event_seq', 0)))
    materials = {(m['name'], m['sha256']): m for m in workspace['materials']}
    sequence = []
    for index, draft in enumerate(images, 1):
        attempts = [a for a in draft['attempts'] if a['status'] == 'succeeded' and a.get('output')]
        output = attempts[-1]['output'] if attempts else None
        material = materials.get((output['name'], output['sha256'])) if output else None
        reference = {'name': output['name'], 'sha256': output['sha256']} if material else None
        matching = [d for d in videos if d['reference'] and reference and
                    (d['reference']['name'], d['reference']['sha256']) ==
                    (reference['name'], reference['sha256'])]
        selected = matching[-1] if matching else None
        sequence.append({'index': index, 'shot_id': draft['shot_id'], 'image_draft_id': draft['draft_id'],
                         'reference': reference, 'approved': bool(material and material['approved']),
                         'video_draft_id': selected['draft_id'] if selected else None,
                         'video_draft_sha256': selected['draft_sha256'] if selected else None})
    return sequence


def _shot_dependency_context(store, run_id):
    writing = store.latest_artifact(run_id, 'writing')
    rows = (writing.structured or {}).get('segments', []) if writing else []
    material = store.latest_artifact(run_id, 'material_plan')
    design = (material.structured or {}).get('visual_design', {}) if material else {}
    intake = store.latest_artifact(run_id, 'intake')
    product = {'brief':store.read_run(run_id).brief,
               'facts':intake.structured or {'artifact_sha256':intake.sha256} if intake else {}}
    return {'rows': rows, 'design': design, 'product': product,
            'source_materials': evidence_source_snapshot(store, run_id)}


def shot_dependencies(store, run_id, shot_id, *, kind, prompt, references, model='',
                      duration=None, resolution=None, context=None):
    from .shot_identity import dependency_hashes
    context = context if context is not None else _shot_dependency_context(store, run_id)
    segment = next((row for index, row in enumerate(context['rows'], 1)
                    if (row.get('shot_id') or f'shot-{index:02d}') == shot_id), None)
    if segment is None:
        raise ValueError('原镜头已不在当前脚本中，不能复用到其他镜头。')
    return dependency_hashes(segment=segment, design=context['design'], product=context['product'],
        source_materials=context['source_materials'], prompt=prompt,
        references=references, kind=kind, model=model, duration=duration, resolution=resolution)


def _reuse_continuity_reference(store, pipeline, run_id, draft, source, baseline,
                                drafts, attempts, hashes, stage_memo, generated_outputs):
    """Resolve the current same-shot frame, without carrying its old approval."""
    references = draft_references(draft)
    if len(references) != 1 or references[0]['purpose'] != 'continuity':
        raise ValueError('历史视频没有一张准确的连续性首帧，不能复用。')
    previous = references[0]
    pair = (previous['name'], previous['sha256'])
    if pair not in generated_outputs:
        if hashes.get(previous['name']) != previous['sha256']:
            raise ValueError('原上传首帧字节缺失或已变化，不能复用。')
        return {key: previous[key] for key in ('name', 'sha256', 'purpose')}
    image = current_draft(drafts, draft['shot_id'], 'image', baseline=baseline,
                          source_sha256=source.sha256)
    if not image:
        raise ValueError('本镜当前首帧尚未准备，请先沿用或完成当前首帧，再复用视频。')
    validate_visual_binding(store, pipeline, run_id, image, stage_memo=stage_memo)
    if any(hashes.get(ref['name']) != ref['sha256'] for ref in draft_references(image)):
        raise ValueError('本镜当前首帧输入的参考字节已变化，请重新核对。')
    latest = next((row for row in reversed(list(attempts.values()))
                   if row.get('draft_id') == image['draft_id']), {})
    output = latest.get('output') or {}
    if latest.get('status') != 'succeeded' or not output:
        raise ValueError('本镜当前首帧结果尚未确认，请先核实原图片任务，再复用视频。')
    if hashes.get(output.get('name')) != output.get('sha256'):
        raise ValueError('本镜当前首帧字节缺失或已变化，不能复用视频。')
    if output['sha256'] != previous['sha256']:
        raise ValueError('本镜当前首帧与历史视频首帧字节不同，不能复用视频。')
    reference = {key: output[key] for key in ('name', 'sha256')}
    reference['purpose'] = 'continuity'
    validate_current_continuity(store, run_id, {
        **draft, 'references': [reference], 'source_snapshot': baseline,
        'source_sha256': source.sha256, 'design_binding': image['design_binding'],
    }, drafts=drafts, attempts=attempts)
    return reference


def reuse_candidates(store, pipeline, run_id, *, drafts=None, attempts=None,
                     baseline=None, hashes=None, stage_memo=None):
    """Read-only comparisons; availability is not approval or execution authority."""
    drafts = draft_records(store, run_id) if drafts is None else drafts
    attempts = attempt_records(store, run_id) if attempts is None else attempts
    if not attempts:
        return []
    baseline = baseline if baseline is not None else source_snapshot(store, run_id)
    historical = [(attempt, drafts.get(attempt.get('draft_id'))) for attempt in attempts.values()
                  if drafts.get(attempt.get('draft_id'), {}).get('source_snapshot', baseline) != baseline]
    if not historical:
        return []
    stage_memo = {} if stage_memo is None else stage_memo
    writing = pipeline.stage_state(run_id, 'writing', stage_memo)
    ready = bool(writing.latest and not writing.stale and writing.integrity_ok and not writing.open_attempt
                 and (pipeline.is_complete(run_id, 'writing', stage_memo) or any(
                     row.get('source_snapshot') == baseline for row in drafts.values())))
    ready = ready and design_status(store, pipeline, run_id, stage_memo=stage_memo)['ready']
    hashes = hashes if hashes is not None else {
        row['name']:row['sha256'] for row in evidence_snapshot(store, run_id)['materials']}
    context = _shot_dependency_context(store, run_id)
    generated_outputs = {(event.get('output', {}).get('name'), event.get('output', {}).get('sha256'))
                         for event in store.read_events(run_id) if event.get('kind') == 'production_output'}
    candidates = []
    for attempt, draft in historical:
        old = draft.get('reuse_dependencies')
        changed, reason, reuse_reference = [], '', None
        references = draft_references(draft)
        try:
            now = shot_dependencies(store, run_id, draft['shot_id'], kind=draft['kind'],
                prompt=draft.get('shot_prompt', ''), references=references,
                model=draft.get('model', ''), duration=draft.get('duration'), resolution=draft.get('resolution'),
                context=context)
            changed = sorted(key for key in set(old or {}) | set(now) if (old or {}).get(key) != now.get(key))
        except ValueError as exc:
            changed, reason = ['shot_removed'], str(exc)
        if draft['kind'] == 'video' and writing.latest and not reason:
            try:
                reuse_reference = _reuse_continuity_reference(store, pipeline, run_id, draft,
                    writing.latest, baseline, drafts, attempts, hashes, stage_memo, generated_outputs)
                now = shot_dependencies(store, run_id, draft['shot_id'], kind=draft['kind'],
                    prompt=draft.get('shot_prompt', ''), references=[reuse_reference],
                    model=draft.get('model', ''), duration=draft.get('duration'), resolution=draft.get('resolution'),
                    context=context)
                changed = sorted(key for key in set(old or {}) | set(now)
                                 if (old or {}).get(key) != now.get(key))
            except ValueError as exc:
                # The script shot still exists even when its current frame is
                # missing or unknown. Preserve its actual dependency changes.
                reuse_reference, reason = None, str(exc)
        output = attempt.get('output') or {}
        if attempt.get('status') != 'succeeded':
            reason = '原任务结果尚未确认或未成功，只查询原任务；不会转成新的生成。'
        elif not output or hashes.get(output.get('name')) != output.get('sha256'):
            reason = '原结果字节缺失或已变化，不能复用。'
        elif not old:
            reason = '历史输入没有逐镜依赖快照，不能证明字节可复用。'
        elif changed:
            reason = reason or '依赖已变化：' + '、'.join(changed)
        elif not ready:
            reason = '当前脚本或共同设计尚未完成并采用；先核对当前版本。'
        candidates.append({'shot_id':draft['shot_id'], 'kind':draft['kind'],
            'source_draft_id':draft['draft_id'], 'source_attempt_id':attempt['attempt_id'],
            'source_version':writing.latest.version if writing.latest else None,
            'source_sha256':writing.latest.sha256 if writing.latest else None,
            **({'reuse_reference':reuse_reference} if draft['kind'] == 'video' else {}),
            'output':{key:output[key] for key in ('name','sha256') if key in output},
            'eligible':not reason, 'changed_dependencies':changed,
            'reason':reason or '逐镜依赖与原结果字节一致，可明确绑定到当前脚本；图审与费用授权不会沿用。'})
    return candidates


def _finish_reuse(store, run_id, draft, source_attempt):
    """Copy verified bytes to a new identity, without provider calls or approvals."""
    attempt_id = 'reuse-' + hashlib.sha256(draft['draft_id'].encode()).hexdigest()[:24]
    existing = attempt_records(store, run_id).get(attempt_id)
    if existing and existing.get('status') == 'succeeded':
        return
    output = source_attempt['output']
    path = resolve(store, run_id, output['name'])
    if not path:
        raise ProductionError('reuse_output_missing', '原结果文件已缺失，不能复用。')
    raw = path.read_bytes()
    if hashlib.sha256(raw).hexdigest() != output['sha256']:
        raise ProductionError('reuse_output_changed', '原结果文件字节已变化，不能复用。')
    name = 'production-' + hashlib.sha256(attempt_id.encode()).hexdigest()[:24] + path.suffix.lower()
    current = resolve(store, run_id, name)
    if current and hashlib.sha256(current.read_bytes()).hexdigest() != output['sha256']:
        raise ProductionError('reuse_output_conflict', '复用结果已有不同字节，未覆盖。')
    if not existing:
        store.append_event(run_id, 'production_attempt', attempt_id=attempt_id,
            draft_id=draft['draft_id'], draft_sha256=draft['draft_sha256'], media_kind=draft['kind'],
            status='reusing', message='正在把已核实字节绑定到当前输入。', output=None,
            provider='local_reuse', reused_from_attempt_id=source_attempt['attempt_id'])
    if not current:
        accept_upload(store, run_id, name, raw)
    reused = {'name':name,'sha256':output['sha256'],'url':material_url(run_id,name)}
    store.append_event(run_id, 'production_output', attempt_id=attempt_id, output=reused)
    store.append_event(run_id, 'production_status', attempt_id=attempt_id,
        update={'status':'succeeded','message':'已复用相同字节；新输出尚未图审，没有提交生成或沿用费用授权。'})


def prepare_draft(store, pipeline, run_id, payload: DraftIn, *, actor='user'):
    """Free, immutable preparation, shared by UI and the controller tool.

    Every refusal here is a ``ProductionError``: it names the actual cause and
    the safe next step instead of asking the reader to re-check parameters that
    were never wrong.
    """
    target = {'kind': payload.kind, 'request_id': payload.request_id,
              'shot_id': payload.shot_id or ''}
    with store.run_lock(run_id):
        store.read_run(run_id)
        fields = payload.model_dump(exclude={'request_id'})
        # Preserve retry identity for requests saved before the list field was
        # introduced. The immutable draft below separately stores its canonical
        # list, while request_payload records exactly the input spelling.
        if not fields['references']:
            fields.pop('references')
        if not fields['reuse_attempt_id']:
            fields.pop('reuse_attempt_id')
        if fields['preserve_prompt_from'] is None:
            fields.pop('preserve_prompt_from')
        try:
            references = normalise_references(payload.kind,
                payload.reference.model_dump() if payload.reference else None,
                [row.model_dump() for row in payload.references])
        except ValueError as exc:
            raise ProductionError('reference_purpose_invalid', str(exc), target=target,
                                  retryable=True, next_action='choose_reference') from None
        if payload.prompt is not None and not payload.prompt.strip():
            raise ProductionError('empty_prompt', '请填写实际发送给生成模型的描述。',
                                  target=target, next_action='supply_prompt')
        if payload.kind == 'video':
            if payload.model != 'wan3.0-video' or not references or payload.duration is None or not payload.resolution:
                raise ProductionError('missing_video_parameters',
                                      '这段视频输入还缺万相 3.0、参考图、时长或清晰度。',
                                      target=target, retryable=True,
                                      next_action='supply_parameters')
        elif payload.model not in {'', 'codex-image'} or payload.duration is not None or payload.resolution is not None:
            raise ProductionError('image_rejects_video_parameters',
                                  '图片使用本机 Codex 默认模型，不接受视频参数。',
                                  target=target, retryable=True, next_action='supply_parameters')
        source = store.latest_artifact(run_id, 'writing')
        if (not source or source.version != payload.source_version or source.sha256 != payload.source_sha256
                or source.digest_algorithm != 'artifact-v2' or not store.verify_artifact(run_id, 'writing', source.version)):
            latest = f'当前脚本是第 {source.version} 版' if source else '当前还没有脚本'
            raise ProductionError('script_version_changed',
                                  f'这份输入要绑定的脚本已经不是当前版本；{latest}。',
                                  target={**target, 'requested_version': payload.source_version,
                                          'current_version': source.version if source else None},
                                  next_action='review_current_script', needs_user_decision=True)
        drafts = draft_records(store, run_id)
        if payload.request_id in drafts:
            row = drafts[payload.request_id]
            if row['request_payload'] != fields:
                raise ProductionError('request_id_reused',
                                      '这个保存请求已有另一份方案，请使用新请求保存新版本。',
                                      target=target, next_action='new_request_id')
            if payload.reuse_attempt_id:
                original = attempt_records(store, run_id).get(payload.reuse_attempt_id)
                if not original or original.get('status') != 'succeeded' or not original.get('output'):
                    raise ProductionError('reuse_unverified', '原任务结果未核实，不能复用或自动重生成。')
                _finish_reuse(store, run_id, row, original)
            return row
        visual = design_status(store, pipeline, run_id)
        if not visual['ready']:
            raise ProductionError('visual_design_missing' if not visual.get('design') else 'visual_design_invalid',
                                  ' '.join(visual['issues']), target=target,
                                  next_action='complete_visual_design')
        parent = None
        if payload.supersedes:
            parent = drafts.get(payload.supersedes)
            if parent is None:
                raise ProductionError(
                    'supersedes_unknown', '要替换的那份输入已经不在记录里，请重新核对当前分镜。',
                    target={**target, 'supersedes': payload.supersedes},
                    next_action='review_current_shots', needs_user_decision=True)
            if parent['kind'] != payload.kind or parent['source_sha256'] != payload.source_sha256:
                raise ProductionError(
                    'supersedes_mismatch', '只能替换同一脚本、同一媒体类型的输入；这份输入属于另一套依据。',
                    target={**target, 'supersedes': payload.supersedes},
                    next_action='review_current_shots', needs_user_decision=True)
            if payload.shot_id and payload.shot_id != parent['shot_id']:
                # Without this, naming one shot while replacing another would
                # retire a shot the user never asked to touch.
                raise ProductionError(
                    'supersedes_mismatch',
                    f'这份输入属于镜头 {parent["shot_id"]}，不能用来替换镜头 {payload.shot_id}。',
                    target={**target, 'supersedes': payload.supersedes,
                            'superseded_shot_id': parent['shot_id']},
                    next_action='review_current_shots', needs_user_decision=True)
            if parent.get('superseded_by'):
                raise ProductionError(
                    'supersedes_already_replaced',
                    '这份输入已经有更新的版本，请替换当前那一份，不要替换历史稿。',
                    target={**target, 'supersedes': payload.supersedes,
                            'current_draft_id': parent['superseded_by']},
                    next_action='review_current_shots', needs_user_decision=True)
        baseline = source_snapshot(store, run_id)
        if parent is not None and parent.get('source_snapshot') != baseline:
            raise ProductionError('supersedes_mismatch',
                                  '要替换的输入属于旧依据，请核对当前分镜并保存新输入。',
                                  target=target, next_action='review_current_shots',
                                  needs_user_decision=True)
        shot_prompt = payload.prompt
        if payload.preserve_prompt_from is not None:
            if parent is None or parent['draft_sha256'] != payload.preserve_prompt_from.expected_sha256:
                raise ProductionError('prompt_source_changed',
                                      '要复用的原描述输入或指纹已变化，请重新读取当前准确输入。',
                                      target=target, next_action='review_current_shots')
            shot_prompt = parent.get('shot_prompt')
            if not isinstance(shot_prompt, str) or not shot_prompt.strip() or len(shot_prompt) > 5000:
                raise ProductionError('prompt_source_unavailable',
                                      '这份输入没有可复用的准确原描述，请重新准备描述；旧输入保留。',
                                      target=target, next_action='refine_shot_input')
        inherited = any(d['source_sha256'] == source.sha256 and d['source_snapshot'] == baseline
                        for d in drafts.values())
        if not pipeline.is_complete(run_id, 'writing') and not inherited:
            raise ProductionError(
                'script_not_adopted',
                '当前脚本还没有被采用。原素材、方向或脚本有变化时，需要先更新并重新确认。',
                target={**target, 'source_version': source.version},
                next_action='adopt_current_script', needs_user_decision=True)
        open_stages = [stage for stage in STAGES
                       if pipeline.stage_state(run_id, stage).open_attempt]
        if open_stages:
            raise ProductionError(
                'stage_attempt_open',
                '还有未结束的创作步骤（' + '、'.join(open_stages) + '），先完成或恢复它再准备制作。',
                target={**target, 'stages': open_stages},
                next_action='resolve_open_attempt', needs_user_decision=True)
        reference_bytes = 0
        for reference in references:
            try:
                raw, _ = read_image(store, run_id, reference['name'], reference['sha256'])
                reference_bytes += len(raw)
            except ValueError as exc:
                raise ProductionError(
                    'reference_unusable', str(exc),
                    target={**target, 'reference': reference},
                    retryable=True, next_action='choose_reference',
                    needs_user_decision=True) from None
        if payload.kind == 'image' and reference_bytes > 24 * 1024 * 1024:
            raise ProductionError('references_too_large', '本镜所有图片参考的合计大小需小于 24 MB。',
                                  target=target, retryable=True, next_action='choose_reference')
        try:
            compiled = compile_visual_input(store, pipeline, run_id,
                source_version=payload.source_version, source_sha256=payload.source_sha256,
                shot_id=payload.shot_id or (parent['shot_id'] if parent else None),
                kind=payload.kind, shot_prompt=shot_prompt, references=references)
        except ValueError as exc:
            status = design_status(store, pipeline, run_id)
            code = 'visual_design_missing' if not status.get('design') else 'visual_design_invalid'
            raise ProductionError(code, str(exc), target=target,
                                  next_action='complete_visual_design') from None
        if len(compiled['compiled_prompt']) > (20_000 if payload.kind == 'video' else 30_000):
            raise ProductionError('compiled_prompt_too_long',
                                  '人物、场景和镜头编译后的描述超出模型限制，请精简本镜输入。',
                                  target=target, next_action='refine_shot_input')
        rate = {'480P': .3, '720P': .6, '1080P': 1.2}.get(payload.resolution)
        estimate = {'currency': 'CNY' if rate else None,
                    'amount': round(rate * payload.duration, 2) if rate else None,
                    'notice': ('北京地域公开原价估算，按生成时长计费；优惠与最终账单以百炼为准。'
                               '此人民币费用不受文字模型美元预算限制。' if rate else
                               '使用现有 Codex 登录额度；图片费用和剩余额度未知，不代表免费。'
                               '本次启动一个生成任务，可能包含多次模型出图调用；费用暂无法预估，异常时会停止本地等待并保留调用记录。'),
                    'source': 'https://help.aliyun.com/zh/model-studio/wan3-0-video' if rate else 'Codex CLI',
                    'as_of': '2026-09-29',
                    'input_sha256': digest({'prompt': compiled['compiled_prompt'],
                                           'references': compiled['references']})}
        draft = {**fields, **compiled, 'prompt': compiled['compiled_prompt'],
                 'shot_prompt': shot_prompt,
                 'reference': ({key: references[0][key] for key in ('name', 'sha256')}
                               if references else None),
                 'draft_id': payload.request_id, 'created_at': utcnow(),
                 'actor': actor, 'request_payload': fields, 'source_snapshot': baseline, 'estimate': estimate,
                 'parameters': {'ratio': 'adaptive', 'audio': True, 'prompt_extend': False} if payload.kind == 'video' else {}}
        # The compiler resolves the exact adopted segment; only a single-shot
        # script can infer an omitted identity. Revisions keep their parent id.
        draft['shot_id'] = compiled['shot_binding']['shot_id']
        draft['supersedes'] = payload.supersedes
        draft['reuse_dependencies'] = shot_dependencies(store, run_id, draft['shot_id'],
            kind=payload.kind, prompt=shot_prompt, references=references, model=payload.model,
            duration=payload.duration, resolution=payload.resolution)
        reused_attempt = None
        if payload.reuse_attempt_id:
            candidate = next((item for item in reuse_candidates(store, pipeline, run_id, drafts=drafts)
                              if item['source_attempt_id'] == payload.reuse_attempt_id), None)
            if not candidate or not candidate['eligible'] or candidate['shot_id'] != draft['shot_id'] or candidate['kind'] != payload.kind:
                raise ProductionError('reuse_ineligible', candidate['reason'] if candidate else '没有可核实的旧结果可供复用。',
                                      target=target, next_action='review_reuse_dependencies')
            if payload.kind == 'video' and references != [candidate['reuse_reference']]:
                raise ProductionError('reuse_continuity_changed',
                                      '本次沿用未绑定本镜当前准确首帧，请重新读取并核对当前素材。',
                                      target=target, next_action='review_current_first_frame')
            old_draft = drafts[candidate['source_draft_id']]
            if old_draft.get('reuse_dependencies') != draft['reuse_dependencies']:
                raise ProductionError('reuse_dependencies_changed', '本次描述、参考或参数与旧结果依赖不同，不能复用字节。',
                                      target=target, next_action='review_reuse_dependencies')
            reused_attempt = attempt_records(store, run_id)[payload.reuse_attempt_id]
            draft['reuse'] = {'source_attempt_id':payload.reuse_attempt_id,
                             'source_draft_id':old_draft['draft_id'],'output':candidate['output']}
            draft['estimate'] = {'currency':None,'amount':None,'provider_invoked':False,
                                 'notice':'本地复用已验证字节，不调用生成服务；旧图审与执行授权不继承。'}
        try:
            validate_current_continuity(store, run_id, draft, drafts=drafts)
        except ValueError as exc:
            raise ProductionError('continuity_frame_stale', str(exc), target=target,
                                  next_action='review_current_first_frame',
                                  needs_user_decision=True) from None
        draft['draft_sha256'] = digest(draft)
        store.append_event(run_id, 'production_draft', draft=draft)
        if reused_attempt:
            _finish_reuse(store, run_id, draft, reused_attempt)
        return draft_records(store, run_id)[payload.request_id]


def validate_video(raw):
    executable = shutil.which('ffmpeg')
    if not executable:
        raise ValueError('本机缺少视频解码工具，已保留提供方任务，可安装后重新取回。')
    with tempfile.TemporaryDirectory(prefix='studio-video-check-') as folder:
        path = Path(folder) / 'result.mp4'
        path.write_bytes(raw)
        result = subprocess.run([executable, '-v', 'error', '-xerror', '-nostdin', '-i', str(path),
            '-map', '0:v:0', '-f', 'null', '-'], capture_output=True, timeout=120, shell=False)
        if result.returncode:
            raise ValueError('返回的视频不能完整解码，保留任务供查询，没有重新生成。')


def assemble_videos(paths: list[Path], cuts: list[dict] | None = None,
                    overlays: list[dict] | None = None) -> bytes:
    """Normalize clips, apply an explicit picture/audio edit, then concatenate."""
    ffmpeg, ffprobe = shutil.which('ffmpeg'), shutil.which('ffprobe')
    if not ffmpeg or not ffprobe:
        raise ValueError('本机缺少 FFmpeg 或 FFprobe，暂不能拼接视频。')
    with tempfile.TemporaryDirectory(prefix='studio-assembly-') as folder:
        root = Path(folder)
        normalized = []
        for index, path in enumerate(paths):
            probe = subprocess.run([ffprobe, '-v', 'error', '-show_streams', '-of', 'json', str(path)],
                                   capture_output=True, timeout=60, shell=False)
            if probe.returncode:
                raise ValueError(f'第 {index + 1} 段视频无法读取，未生成拼接片。')
            streams = json.loads(probe.stdout).get('streams', [])
            if not any(stream.get('codec_type') == 'video' for stream in streams):
                raise ValueError(f'第 {index + 1} 段缺少视频轨，未生成拼接片。')
            has_audio = any(stream.get('codec_type') == 'audio' for stream in streams)
            target = root / f'{index:02d}.mp4'
            command = [ffmpeg, '-v', 'error', '-xerror', '-nostdin', '-y', '-i', str(path)]
            if not has_audio:
                command += ['-f', 'lavfi', '-i', 'anullsrc=channel_layout=stereo:sample_rate=48000']
            command += ['-map', '0:v:0', '-map', '0:a:0' if has_audio else '1:a:0',
                        '-vf', 'scale=720:1280:force_original_aspect_ratio=decrease,'
                               'pad=720:1280:(ow-iw)/2:(oh-ih)/2,setsar=1,fps=30',
                        '-af', 'apad', '-c:v', 'libx264', '-preset', 'medium', '-crf', '20',
                        '-pix_fmt', 'yuv420p', '-c:a', 'aac', '-ar', '48000', '-ac', '2',
                        '-shortest', str(target)]
            result = subprocess.run(command, capture_output=True, timeout=600, shell=False)
            if result.returncode:
                raise ValueError(f'第 {index + 1} 段本地转码失败，原片段已保留。')
            normalized.append(target)
        edited = []
        if cuts:
            durations = []
            for path in normalized:
                probe = subprocess.run([ffprobe, '-v', 'error', '-show_entries', 'format=duration',
                    '-of', 'default=noprint_wrappers=1:nokey=1', str(path)],
                    capture_output=True, timeout=60, shell=False)
                if probe.returncode:
                    raise ValueError('本地片段时长无法核对，未生成拼接片。')
                durations.append(float(probe.stdout.strip()))
            for index, cut in enumerate(cuts):
                video_index, audio_index = cut['clip_index'] - 1, cut['audio_clip_index'] - 1
                start, audio_start, duration = (cut['start_seconds'], cut['audio_start_seconds'],
                                                 cut['duration_seconds'])
                if (not 0 <= video_index < len(normalized) or not 0 <= audio_index < len(normalized)
                        or start + duration > durations[video_index] + .06
                        or audio_start + duration > durations[audio_index] + .06):
                    raise ValueError(f'剪辑第 {index + 1} 段超出已取回片段的实际时长，原片段已保留。')
                target = root / f'cut-{index:02d}.mp4'
                result = subprocess.run([ffmpeg, '-v', 'error', '-xerror', '-nostdin', '-y',
                    '-ss', str(start), '-i', str(normalized[video_index]),
                    '-ss', str(audio_start), '-i', str(normalized[audio_index]),
                    '-map', '0:v:0', '-map', '1:a:0', '-t', str(duration),
                    '-af', 'apad', '-c:v', 'libx264', '-preset', 'medium', '-crf', '20',
                    '-pix_fmt', 'yuv420p', '-c:a', 'aac', '-ar', '48000', '-ac', '2', str(target)],
                    capture_output=True, timeout=300, shell=False)
                if result.returncode:
                    raise ValueError(f'剪辑第 {index + 1} 段失败，原片段已保留。')
                edited.append(target)
        else:
            edited = normalized
        output = root / 'assembled.mp4'
        inputs = [part for path in edited for part in ('-i', str(path))]
        tracks = ''.join(f'[{index}:v:0][{index}:a:0]' for index in range(len(edited)))
        filter_complex = f'{tracks}concat=n={len(edited)}:v=1:a=1[v][a]'
        video_map = '[v]'
        if overlays:
            fonts = [Path(os.environ.get('WINDIR', 'C:/Windows')) / 'Fonts' / 'arial.ttf',
                     Path('/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf'),
                     Path('/System/Library/Fonts/Supplemental/Arial.ttf')]
            font = next((candidate for candidate in fonts if candidate.is_file()), None)
            if not font:
                raise ValueError('本机缺少可用于片内字卡的字体，原片段已保留。')
            shutil.copyfile(font, root / 'overlay-font.ttf')
        for index, overlay in enumerate(overlays or []):
            (root / f'overlay-{index}.txt').write_text(overlay['text'], encoding='utf-8')
            start, end = overlay['start_seconds'], overlay['start_seconds'] + overlay['duration_seconds']
            next_map = f'[caption{index}]'
            filter_complex += (f';{video_map}drawtext=textfile=overlay-{index}.txt:fontfile=overlay-font.ttf:'
                'fontcolor=white:fontsize=46:borderw=2:bordercolor=black:'
                f"x=(w-text_w)/2:y=h*0.12:enable='between(t,{start},{end})'{next_map}")
            video_map = next_map
        result = subprocess.run([ffmpeg, '-v', 'error', '-xerror', '-nostdin', '-y',
            *inputs, '-filter_complex', filter_complex, '-map', video_map, '-map', '[a]',
            '-c:v', 'libx264', '-preset', 'medium', '-crf', '20', '-pix_fmt', 'yuv420p',
            '-c:a', 'aac', '-ar', '48000', '-ac', '2', '-movflags', '+faststart', str(output)],
            capture_output=True, timeout=600, shell=False, cwd=root)
        if result.returncode:
            raise ValueError('本地拼接失败，原片段已保留。')
        if output.stat().st_size > MAX_UPLOAD_BYTES:
            raise ValueError('拼接片超过工作台 64 MB 素材上限，原片段已保留。')
        raw = output.read_bytes()
        validate_video(raw)
        return raw


#: How long a failed image-capability probe stands before it is retried. The
#: probe spawns the Codex CLI, so a page render should not pay for it every
#: time, but a probe that failed describes this moment, not the machine.
IMAGE_PROBE_RETRY_SECONDS = 15


class Production:
    def __init__(self, jobs, connections, settings, learning, *, client_factory=None,
                 image_factory=None, video_factory=None, poll_delay=3, poll_count=200):
        self.jobs, self.store, self.pipeline = jobs, jobs.store, jobs.pipeline
        self.connections, self.settings, self.learning = connections, settings, learning
        self.client_factory = client_factory
        self.image_factory, self.video_factory = image_factory, video_factory
        self.poll_delay, self.poll_count = poll_delay, poll_count
        self.nonces = {}
        self._image_capability = None
        self._image_probe_at = None
        self._image_probe_failure = None

    def image_client(self):
        if self.image_factory:
            return self.image_factory()
        from .agents.codex_image import CodexImageClient
        return CodexImageClient()

    def image_model_selection(self):
        """The saved material role controls Codex image turns when routed to Codex."""
        config = self.connections.public()
        binding = config['roles']['material']
        connection = next(c for c in config['connections'] if c['id'] == binding['connection'])
        return {'revision': config['revision'],
                'model': binding['model'] if connection['provider'] == 'codex_cli' else ''}

    def video_client(self):
        if self.video_factory:
            return self.video_factory()
        from .agents.wan_video import WanVideoClient
        return WanVideoClient()

    def image_probe(self):
        """The image capability answer, re-checked after a failure.

        Only an answer that came back is kept for the life of the process. A
        probe that raised used to be cached the same way, so one hiccup — a
        busy machine, a CLI mid-upgrade — disabled image generation until the
        service restarted, and nothing on the page distinguished that from a
        connection that had genuinely never worked. A failed probe is retried
        after ``IMAGE_PROBE_RETRY_SECONDS``; the reason carries the exception
        class name only, because the page shows it.
        """
        if self._image_capability is not None:
            return self._image_capability
        now = time.monotonic()
        if self._image_probe_at is not None and now - self._image_probe_at < IMAGE_PROBE_RETRY_SECONDS:
            return self._image_probe_failure
        # Other workspace requests may arrive while the CLI probe is running.
        # Give them a valid temporary answer instead of returning None.
        self._image_probe_failure = {'available': False, 'verified': False,
            'reason': '本机 Codex 图片连接正在检查，请稍后重新打开制作页。'}
        self._image_probe_at = now
        try:
            self._image_capability = self.image_client().capability()
        except Exception as exc:
            self._image_probe_failure = {'available': False, 'verified': False,
                'reason': '本机 Codex 图片连接暂未通过能力检查，请检查 CLI 安装和登录状态；'
                          f'重新打开制作页会再检查一次。（{type(exc).__name__}）'}
        return self._image_capability or self._image_probe_failure

    def capabilities(self):
        image = {**self.image_probe(), 'label': 'Codex 图片生成'}
        image_model = self.image_model_selection()
        image['controller_model'] = image_model['model']
        image['connection_revision'] = image_model['revision']
        if image.get('available'):
            image['reason'] = '本机原生图片协议可用；尚未完成真实出图验收。'
        from .agents.wan_video import existing_credentials_available
        available = bool(self.video_factory) or existing_credentials_available()
        video = {'available': available, 'reason': '已发现原百炼凭据；尚未完成本站真实生成验收。' if available else '未找到原百炼凭据，请先配置北京地域连接。'}
        video = {**video, 'label': '阿里百炼 · 通义万相 3.0', 'verified': False,
                 'models': [{'id': 'wan3.0-video', 'label': '通义万相 3.0',
                             'resolutions': ['480P', '720P', '1080P'], 'durations': {'min': 2, 'max': 30}}]}
        if not shutil.which('ffmpeg') and not self.video_factory:
            video.update(available=False, reason='本机缺少 FFmpeg，暂不能校验并保存视频结果。')
        return {'image': image, 'video': video}

    def nonce(self, run_id):
        return self.nonces.setdefault(run_id, secrets.token_urlsafe(32))

    def require_nonce(self, run_id, nonce):
        if not nonce or not secrets.compare_digest(nonce, self.nonce(run_id)):
            raise ValueError('确认页面已失效，请重新打开制作页面后再确认。')

    def event(self, run_id, kind, **fields):
        with self.store.run_lock(run_id):
            return self.store.append_event(run_id, kind, **fields)

    def attempts(self, run_id):
        return attempt_records(self.store, run_id, self.jobs.ledger.entries(run_id),
                               execution_active=self.jobs.active is not None)

    def status(self, run_id, attempt_id, **update):
        self.event(run_id, 'production_status', attempt_id=attempt_id, update=update)

    def approvals(self, run_id):
        approved = {}
        for e in self.store.read_events(run_id):
            if e.get('kind') == 'production_material_approval':
                approved[(e['name'], e['sha256'])] = e['approved']
        return approved

    def get_draft(self, run_id, draft_id, expected=None, check_source=False):
        d = draft_records(self.store, run_id).get(draft_id)
        if not d or expected and expected != d['draft_sha256']:
            raise ValueError('制作方案已变化，请重新打开准确版本。')
        if check_source and d['source_snapshot'] != source_snapshot(self.store, run_id):
            raise ValueError('方案依据已变化，请根据当前资料重新保存并检查制作方案。')
        if check_source and not d.get('is_current'):
            raise ValueError('这份镜头输入已被新版替换，请重新打开当前镜头并核对授权。')
        if check_source:
            validate_visual_binding(self.store, self.pipeline, run_id, d)
            validate_current_continuity(self.store, run_id, d)
            for reference in d['references']:
                read_image(self.store, run_id, reference['name'], reference['sha256'])
        return d

    def validate_generation_set(self, run_id, authorized, *, _draft_reader=None):
        """Revalidate every pinned revision, not only the next item in a batch."""
        with self.store.run_lock(run_id):
            reader = self.get_draft if _draft_reader is None else _draft_reader
            try:
                selected = [reader(run_id, draft_id, expected, True)
                            for draft_id, expected in authorized]
            except ValueError as exc:
                raise PipelineError('generation_authorization_stale', str(exc)) from None
            identities = [(row['kind'], row['source_snapshot'], row['shot_id']) for row in selected]
            if len(identities) != len(set(identities)):
                raise PipelineError('generation_duplicate_shot',
                                    '一次授权不能重复提交同一镜头，请重新核对准确的当前输入集合。')
            for row in selected:
                if row.get('reuse'):
                    raise PipelineError('generation_reuse_only',
                                        '这份输入仅用于本地复用；重新生成需保存新输入并重新核对费用。')
                if row['kind'] == 'video' and not self.approvals(run_id).get(
                        (row['references'][0]['name'], row['references'][0]['sha256'])):
                    raise PipelineError('generation_reference_changed',
                                        '参考图确认已变化，请重新核对这组准确输入并授权。')
        return selected

    def validate_submission_authorization(self, run_id, attempt_id, authorized):
        try:
            self.validate_generation_set(run_id, authorized)
        except PipelineError as exc:
            self.jobs.ledger.settle_media_call(run_id, attempt_id, quantity=0, ok=False,
                note='准确生成授权已失效，未调用提供方。')
            self.status(run_id, attempt_id, status='failed', message=str(exc))
            raise

    def state(self, run_id):
        """The whole production picture, in a form any reader may see.

        ``Production.workspace`` used to be the only projection, and it was
        shaped for the 制作 page: it had the nonce, browser URLs and the page's own
        affordances. The controller read a thinner, different thing —
        ``draft_records`` — which initialises ``attempts`` to ``[]``. So the
        question "why did this storyboard not come out" reached the controller
        with no attempts in it at all, while the answer was sitting in
        ``Production.attempts``.

        The projection itself lives in one function so the page and the
        controller cannot disagree about which shot is blocked. This method adds
        only what needs the running service: whether a job is active here and how
        many calls are unaccounted for.
        """
        with self.store.run_lock(run_id):
            result = _read_state_without_service(
                self.store, self.pipeline, run_id, ledger=self.jobs.ledger,
                execution_active=self.jobs.active is not None)
            result['active'] = bool(self.jobs.active)
            result['unresolved_calls'] = self.jobs.ledger.totals().unknown_calls
        return result

    def workspace(self, run_id, *, for_agent=False):
        result = self.state(run_id)
        if for_agent:
            # Capabilities without the page's own affordances. The controller
            # needs to know whether an attempt is even possible; it must not
            # receive a nonce, which is the browser's approval channel.
            result['capabilities'] = {
                kind: {k: v for k, v in self.capabilities()[kind].items()
                       if k in {'available', 'verified', 'reason', 'label'}}
                for kind in ('image', 'video')}
            return result
        # The page needs the media URLs; the controller is served by
        # ``agent_production_state``, which strips them again.
        result['materials'] = [{**m, 'url': material_url(run_id, m['name'])}
                               for m in result['materials']]
        for draft in result['drafts']:
            if draft.get('reference'):
                draft['reference'] = {**draft['reference'],
                                      'url': material_url(run_id, draft['reference']['name'])}
            valid = {(material['name'], material['sha256']) for material in result['materials']}
            draft['references'] = [{**reference,
                **({'url': material_url(run_id, reference['name'])}
                   if (reference['name'], reference['sha256']) in valid else {})}
                for reference in draft['references']]
        result.update(capabilities=self.capabilities(), nonce=self.nonce(run_id),
                      recovery_modes=['retry_with_unknown_cost'])
        return result


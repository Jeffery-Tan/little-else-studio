class ProductionError(ValueError):
    """A preparation failure that still says what to do about it.

    ``prepare_draft`` refuses for reasons that need different answers: the script
    moved on, the script was never adopted, an upstream fact changed, a reference
    image is unusable, a stage attempt was left open, and so on. Collapsing them
    into one sentence left the controller unable to choose a next step and left
    Jeffery re-checking parameters that were never the problem.

    The contract is deliberately the union of what both audiences need: the
    controller reads ``code``/``retryable``/``next_action``, and the record keeps
    a sentence a person can act on. ``next_action`` and ``needs_user_decision``
    describe the *safe* next step, never a permission.
    """

    def __init__(self, code: str, message: str, *, target: dict | None = None,
                 retryable: bool = False, next_action: str = '',
                 needs_user_decision: bool = False):
        super().__init__(message)
        self.code = code
        self.target = target or {}
        self.retryable = retryable
        self.next_action = next_action
        self.needs_user_decision = needs_user_decision

    def to_dict(self) -> dict:
        return {'code': self.code, 'message': str(self), 'target': self.target,
                'retryable': self.retryable, 'next_action': self.next_action,
                'needs_user_decision': self.needs_user_decision}



    def prepare_generation(self, run_id, draft_id, payload, *, authorized=None, _draft_reader=None):
        self.require_nonce(run_id, payload.nonce)
        if not payload.consent:
            raise ValueError('请核对图片、实际描述与费用后确认本次生成。')
        reader = self.get_draft if _draft_reader is None else _draft_reader
        d = reader(run_id, draft_id, payload.expected_sha256, True)
        authorized = tuple(authorized or [(draft_id, payload.expected_sha256)])
        self.validate_generation_set(run_id, authorized, _draft_reader=_draft_reader)
        # Submission recovery prevents duplicate remote jobs, independently of
        # accounting: a completed output with unknown billing is not a blocker.
        related = {row['draft_id'] for row in draft_records(self.store, run_id).values()
                   if row['kind'] == d['kind'] and row['shot_id'] == d['shot_id']
                   and row['source_snapshot'] == d['source_snapshot']}
        if any(a['draft_id'] in related and a['status'] in {
                'queued', 'running', 'preparing', 'submitting', 'submitted',
                'downloading', 'retrieve_failed', 'unknown', 'submission_unknown', 'recovering', 'cancelling'}
               for a in self.attempts(run_id).values()):
            raise ValueError('已有制作任务未确认结束，请查询原任务结果，不要重复提交。')
        if d['kind'] == 'video' and not self.approvals(run_id).get(
                (d['references'][0]['name'], d['references'][0]['sha256'])):
            raise ValueError('请打开并确认这一版参考图，之后才能提交视频。')
        cap = self.capabilities()[d['kind']]
        if not cap.get('available'):
            raise ValueError(cap.get('reason') or '此生成连接暂不可用。')
        image_model = self.image_model_selection() if d['kind'] == 'image' else None
        if image_model and image_model['model'] and payload.expected_connection_revision is None:
            raise ValueError('请刷新制作页面，核对已选 Codex 模型后再确认生成。')
        if (image_model and payload.expected_connection_revision is not None
                and payload.expected_connection_revision != image_model['revision']):
            raise ValueError('模型设置已变化，请重新打开制作页面并核对本次生成模型。')
        self.jobs.ledger.ensure_within_budget()
        raw = [read_image(self.store, run_id, reference['name'], reference['sha256'])[0]
               for reference in d['references']]
        client = self.video_client() if d['kind'] == 'video' else self.image_client()
        endpoint = None
        if d['kind'] == 'video':
            from .agents.wan_video import existing_endpoint, build_payload, WanVideoRequest, WanVideoError
            try:
                endpoint = client.endpoint if self.video_factory else existing_endpoint()
                build_payload(WanVideoRequest(prompt=d['prompt'], image_bytes=raw[0],
                    image_sha256=d['references'][0]['sha256'], duration=d['duration'], resolution=d['resolution'], **d['parameters']))
            except WanVideoError as exc:
                raise ValueError(str(exc)) from None
        attempt_id = payload.request_id
        if attempt_id in self.attempts(run_id):
            raise ValueError('此生成记录已经存在，请查询原任务，不要重新提交。')
        def run(_text, emit, check_cancel):
            check_cancel()
            with self.jobs.ledger.call_guard():
                self.validate_generation_set(run_id, authorized)
                if image_model and self.image_model_selection() != image_model:
                    raise PipelineError('generation_model_changed',
                                        '模型设置已变化，请重新核对当前输入与模型后授权。')
                self.event(run_id, 'production_attempt', attempt_id=attempt_id, draft_id=draft_id,
                    draft_sha256=d['draft_sha256'], media_kind=d['kind'], status='preparing',
                    message='正在准备本次生成。', output=None, endpoint=endpoint)
                self.jobs.ledger.begin_media_call(run_id, call_id=attempt_id,
                    model=(image_model['model'] or 'codex-image') if image_model else d['model'],
                    provider='dashscope' if d['kind'] == 'video' else 'codex_cli',
                    usage_unit='video_seconds' if d['kind'] == 'video' else 'images')
                self.status(run_id, attempt_id, status='submitting', message='已记录本次请求，正在提交。')
                emit({'type': 'status', 'message': '正在生成；关闭页面不取消提供方任务。'})
                if d['kind'] == 'video':
                    self.submit_video(run_id, attempt_id, d, raw[0], client, check_cancel, authorized)
                else:
                    self.submit_image(run_id, attempt_id, d, raw, client, check_cancel,
                                      image_model['model'], authorized)
                attempt = self.attempts(run_id)[attempt_id]
            return outcome(attempt, '本次制作状态已保存，请在制作页查看结果与用量。')
        return run, {'provider': 'dashscope' if d['kind'] == 'video' else 'codex_cli',
                     'model': (image_model['model'] or 'codex-default') if image_model else d['model'],
                     'draft_id': draft_id, 'draft_sha256': d['draft_sha256'], 'estimate': d['estimate']}

    def prepare_batch_generation(self, run_id, payload: BatchGenerateIn):
        """Reuse verified copies only during this one locked, read-only preflight."""
        with self.store.run_lock(run_id):
            owner_thread = threading.get_ident()
            active = True
            checked = {}

            def read_checked(requested_run, draft_id, expected=None, check_source=False):
                if (not active or threading.get_ident() != owner_thread
                        or requested_run != run_id or check_source is not True):
                    raise ValueError('本次生成预检已失效，须重新核对准确输入。')
                key = (requested_run, draft_id, expected, check_source)
                if key not in checked:
                    checked[key] = deepcopy(self.get_draft(requested_run, draft_id, expected, True))
                return deepcopy(checked[key])

            try:
                return self._prepare_batch_generation(run_id, payload, read_checked)
            finally:
                active = False
                checked.clear()

    def _prepare_batch_generation(self, run_id, payload: BatchGenerateIn, draft_reader):
        """One user decision starts pinned shots in order, stopping on uncertainty."""
        self.require_nonce(run_id, payload.nonce)
        if not payload.consent:
            raise ValueError('请先核对整组制作描述、参考和费用。')
        workspace = self.workspace(run_id, for_agent=True)
        selected = [draft_reader(run_id, item.draft_id, item.expected_sha256, True)
                    for item in payload.drafts]
        kinds = {draft['kind'] for draft in selected}
        if len(kinds) != 1:
            raise ValueError('图片与视频不能混在同一组生成任务中。')
        kind = kinds.pop()
        if (kind == 'image' and self.image_model_selection()['model']
                and payload.expected_connection_revision is None):
            raise ValueError('请刷新制作页面，核对已选 Codex 模型后再确认整组生成。')
        image_connection_revision = (payload.expected_connection_revision
                                     if payload.expected_connection_revision is not None
                                     else self.image_model_selection()['revision']) if kind == 'image' else None
        if workspace['unresolved_attempts']:
            raise ValueError('整组仍有任务未核实；先处理原任务，不能跳过后续片段。')
        ids = [item.draft_id for item in payload.drafts]
        if len(ids) != len(set(ids)):
            raise ValueError('同一制作方案不能在一次任务中重复生成。')
        authorized = tuple((item.draft_id, item.expected_sha256) for item in payload.drafts)
        self.validate_generation_set(run_id, authorized, _draft_reader=draft_reader)
        if kind == 'video':
            sequence = workspace['video_sequence']
            if len(sequence) < 2 or any(not shot['approved'] or not shot['video_draft_id'] for shot in sequence):
                raise ValueError('请先确认整组首帧，并为每张图准备对应的视频输入。')
            drafts_by_id = {draft['draft_id']: draft for draft in workspace['drafts']}
            expected = [shot['video_draft_id'] for shot in sequence if not any(
                a['status'] == 'succeeded' and a.get('output')
                for a in drafts_by_id[shot['video_draft_id']]['attempts'])]
            if ids != expected:
                raise ValueError('请按当前分镜顺序提交全部未完成的视频段，不能跳过或替换准确输入。')
        # Freeze the verified delivery format with this exact submitted batch.
        photo = kind == 'image' and content_format(self.store.read_events(run_id)) == 'photo'
        # Display ordinals come from the same current-shot projection as the
        # UI. A subset's position in this batch is not its source page number.
        photo_ordinals = []
        for draft in selected:
            matches = [shot for shot in workspace.get('shots', {}).get(kind, {}).get('shots', [])
                       if shot.get('draft_id') == draft['draft_id']
                       and shot.get('draft_sha256') == draft['draft_sha256']
                       and shot.get('shot_id') == draft.get('shot_id')]
            ordinal = matches[0].get('ordinal') if len(matches) == 1 else None
            photo_ordinals.append(ordinal if type(ordinal) is int and 0 < ordinal <= 9999 else None)
        prepared = []
        for index, item in enumerate(payload.drafts):
            attempt_id = 'batch.' + digest({'request_id': payload.request_id,
                                            'index': index, 'draft_id': item.draft_id})
            action = ActionIn(request_id=attempt_id, expected_sha256=item.expected_sha256,
                              consent=True, nonce=payload.nonce,
                              expected_connection_revision=image_connection_revision)
            runner, _ = self.prepare_generation(run_id, item.draft_id, action, authorized=authorized,
                                                _draft_reader=draft_reader)
            prepared.append(runner)

        def run(_text, emit, check_cancel):
            self.validate_generation_set(run_id, authorized)
            completed = 0
            label = '视频段' if kind == 'video' else '首帧'
            for index, runner in enumerate(prepared, 1):
                check_cancel()
                page = photo_ordinals[index - 1]
                target = f'第 {page:02d} 页图片' if page is not None else '图文图片'
                message = (f'正在生成{target}（本次 {index}/{len(prepared)} 张）。' if photo else
                           f'正在生成第 {index}/{len(prepared)} 个{label}。')
                emit({'type': 'status', 'message': message})
                result = runner('', emit, check_cancel)
                if result.stopped_because != 'done':
                    failure = (f'本次已完成 {completed}/{len(prepared)} 张；{target}未完成：'
                               f'{result.text}。其余所选页面没有提交。' if photo else
                               f'已完成 {completed}/{len(prepared)} 个；第 {index} 个未完成：'
                               f'{result.text}。其余{label}没有提交。')
                    return SimpleNamespace(stopped_because='incomplete', rounds=index,
                                           used_tools=[], text=failure)
                completed += 1
            return done((f'本次 {completed} 张图文图片已生成并保存。' if photo else
                         f'{completed} 个{label}已生成并保存。')
                        + ('请逐页查看图片并核对商品结构、图内文案与发布 caption。' if photo else
                           '请在成片区查看并拼接。' if kind == 'video' else
                           '请在画面区查看，确认准确图片后再继续视频制作。'))

        return run, {'provider': 'dashscope' if kind == 'video' else 'codex_cli',
                     'kind': kind + '_batch',
                     'drafts': [{'draft_id': item.draft_id, 'draft_sha256': item.expected_sha256}
                                for item in payload.drafts]}

    def save_edit_plan(self, run_id, payload: EditPlanIn):
        with self.store.run_lock(run_id):
            fields = payload.model_dump()
            existing = edit_plan_records(self.store, run_id).get(payload.request_id)
            if existing:
                if existing['request_payload'] != fields:
                    raise ValueError('这个保存请求已有另一份剪辑计划，请使用新请求。')
                return existing
            source = self.store.latest_artifact(run_id, 'writing')
            if (not source or source.version != payload.source_version or source.sha256 != payload.source_sha256
                    or source.digest_algorithm != 'artifact-v2'
                    or not self.store.verify_artifact(run_id, 'writing', source.version)
                    or not self.pipeline.is_complete(run_id, 'writing')):
                raise ValueError('剪辑计划必须绑定当前已确认的准确脚本。')
            workspace = self.workspace(run_id, for_agent=True)
            images = [shot['image_draft_id'] for shot in workspace['video_sequence']]
            if len(images) < 2:
                raise ValueError('请先准备至少两条分镜首帧方案。')
            total = sum(cut.duration_seconds for cut in payload.cuts)
            if total > 120:
                raise ValueError('剪辑计划总时长不能超过 120 秒。')
            for cut in payload.cuts:
                if cut.clip_index > len(images) or cut.audio_clip_index > len(images):
                    raise ValueError('剪辑计划引用了不存在的片段。')
            if any(overlay.start_seconds + overlay.duration_seconds > total + .001
                   for overlay in payload.overlays):
                raise ValueError('字卡超出了剪辑计划的总时长。')
            plan = {'request_id': payload.request_id, 'request_payload': fields,
                    'source_version': source.version, 'source_sha256': source.sha256,
                    'source_snapshot': source_snapshot(self.store, run_id),
                    'image_draft_ids': images, 'cuts': [cut.model_dump() for cut in payload.cuts],
                    'overlays': [overlay.model_dump() for overlay in payload.overlays],
                    'confirmed_product': payload.confirmed_product,
                    'duration_seconds': round(total, 3), 'created_at': utcnow()}
            plan['plan_sha256'] = digest(plan)
            self.event(run_id, 'production_edit_plan', plan=plan)
            return plan

    def prepare_assembly(self, run_id, payload: AssemblyIn):
        workspace = self.workspace(run_id, for_agent=True)
        sequence = workspace['video_sequence']
        plan = workspace['edit_plan']
        if not plan or plan['request_id'] != payload.edit_plan_id or plan['plan_sha256'] != payload.edit_plan_sha256:
            raise ValueError('请先核对绑定当前脚本与分镜的准确剪辑计划。')
        if len(sequence) < 2 or len(payload.clips) != len(sequence):
            raise ValueError('请先完成当前分镜的全部视频段，再按顺序拼接。')
        drafts = {d['draft_id']: d for d in workspace['drafts']}
        attempts = self.attempts(run_id)
        unresolved = {'queued', 'running', 'preparing', 'submitting', 'submitted',
                      'downloading', 'retrieve_failed', 'unknown', 'submission_unknown',
                      'recovering', 'cancelling'}
        frozen = []
        for shot, item in zip(sequence, payload.clips):
            if not shot['approved'] or item.draft_id != shot['video_draft_id'] or item.draft_sha256 != shot['video_draft_sha256']:
                raise ValueError('视频顺序或参考图已变化，请重新打开成片区核对。')
            draft = drafts[item.draft_id]
            if any(attempt['status'] in unresolved for attempt in draft['attempts']):
                raise ValueError('仍有视频任务待核实，不能拼接未完成的结果。')
            attempt = attempts.get(item.attempt_id)
            if (not attempt or attempt['draft_id'] != item.draft_id
                    or attempt['draft_sha256'] != item.draft_sha256
                    or attempt['status'] != 'succeeded' or not attempt.get('output')
                    or (attempt['output']['name'], attempt['output']['sha256']) != (item.name, item.sha256)):
                raise ValueError('有片段不是当前准确视频方案的已完成结果。')
            path = resolve(self.store, run_id, item.name)
            if not path or path.suffix.lower() != '.mp4' or hashlib.sha256(path.read_bytes()).hexdigest() != item.sha256:
                raise ValueError('有视频片段文件已变化或丢失，未开始拼接。')
            frozen.append({'draft_id': item.draft_id, 'draft_sha256': item.draft_sha256,
                           'attempt_id': item.attempt_id, 'name': item.name, 'sha256': item.sha256})
        baseline = source_snapshot(self.store, run_id)
        attempt_id = 'assembly.' + digest({'request_id': payload.request_id,
                                           'edit_plan_sha256': plan['plan_sha256'], 'clips': frozen})

        def run(_text, emit, check_cancel):
            check_cancel()
            self.event(run_id, 'production_attempt', attempt_id=attempt_id,
                draft_id='local-assembly', draft_sha256=digest(frozen), media_kind='assembly',
                status='preparing', message='正在本地拼接已取回的片段。', output=None)
            try:
                current = self.workspace(run_id, for_agent=True)['video_sequence']
                if source_snapshot(self.store, run_id) != baseline or len(current) != len(frozen):
                    raise ValueError('脚本或分镜已变化，请重新核对后拼接。')
                paths = []
                for shot, item in zip(current, frozen):
                    check_cancel()
                    if shot['video_draft_id'] != item['draft_id'] or not shot['approved']:
                        raise ValueError('视频方案或图审已变化，请重新核对后拼接。')
                    path = resolve(self.store, run_id, item['name'])
                    if not path or hashlib.sha256(path.read_bytes()).hexdigest() != item['sha256']:
                        raise ValueError('片段文件已变化，未生成拼接片。')
                    paths.append(path)
                emit({'type': 'status', 'message': f'正在本地拼接 {len(paths)} 段视频。'})
                raw = assemble_videos(paths, plan['cuts'], plan['overlays'])
                check_cancel()
                if source_snapshot(self.store, run_id) != baseline:
                    raise ValueError('拼接期间脚本或素材依据发生变化，结果未采用。')
                output = self.save_output(run_id, attempt_id, raw, '.mp4')
                assembly = {'request_id': payload.request_id, 'attempt_id': attempt_id,
                            'source_snapshot': baseline, 'edit_plan_id': plan['request_id'],
                            'edit_plan_sha256': plan['plan_sha256'], 'clips': frozen, 'output': output,
                            'created_at': utcnow(), 'method': 'ffmpeg-script-edit'}
                self.event(run_id, 'production_assembly', assembly=assembly)
                self.status(run_id, attempt_id, status='succeeded', message='本地成片已保存，请播放核对声画。')
                return done('本地成片已保存，请在成片区播放并核对。')
            except (ValueError, OSError, subprocess.TimeoutExpired) as exc:
                self.status(run_id, attempt_id, status='failed', message=str(exc))
                return SimpleNamespace(stopped_because='incomplete', rounds=1, used_tools=[], text=str(exc))

        return run, {'provider': 'local_ffmpeg', 'kind': 'assembly', 'clips': frozen}

    def save_output(self, run_id, attempt_id, raw, suffix):
        name = f'production-{hashlib.sha256(attempt_id.encode()).hexdigest()[:24]}{suffix}'
        sha = hashlib.sha256(raw).hexdigest()
        with self.store.run_lock(run_id):
            path = resolve(self.store, run_id, name)
            if path:
                if hashlib.sha256(path.read_bytes()).hexdigest() != sha:
                    raise ValueError('本次结果文件已有不同内容，已保留，未覆盖。')
            else:
                accept_upload(self.store, run_id, name, raw)
            out = {'name': name, 'sha256': sha, 'url': material_url(run_id, name)}
            self.event(run_id, 'production_output', attempt_id=attempt_id, output=out)
            return out

    def submit_video(self, run_id, attempt_id, d, raw, client, check_cancel, authorized):
        from .agents.wan_video import WanVideoRequest, WanVideoError
        self.validate_submission_authorization(run_id, attempt_id, authorized)
        try:
            result = client.submit(WanVideoRequest(prompt=d['prompt'], image_bytes=raw,
                image_sha256=d['references'][0]['sha256'], duration=d['duration'], resolution=d['resolution'], **d['parameters']),
                expected_endpoint=self.attempts(run_id)[attempt_id]['endpoint'])
        except WanVideoError as exc:
            if not exc.submission_unknown:
                self.jobs.ledger.settle_media_call(run_id, attempt_id, quantity=0, ok=False,
                                                  note='提供方明确未接受生成请求。')
            self.status(run_id, attempt_id, status='unknown' if exc.submission_unknown else 'failed',
                        message='提交结果待核实，请先核对百炼任务，不能重复提交。' if exc.submission_unknown else str(exc))
            return
        except Exception as exc:
            # Class name only. A provider error can carry a signed URL, and this
            # message is written to the run journal and shown on the page.
            self.status(run_id, attempt_id, status='unknown',
                        message=f'提交结果待核实，请先核对百炼任务，不能重复提交。（{type(exc).__name__}）')
            return
        self.status(run_id, attempt_id, status='submitted', task_id=result.task_id, endpoint=result.endpoint,
                    message='百炼已接收任务，正在等待视频。')
        self.poll_video(run_id, attempt_id, d, client, check_cancel)

    def poll_video(self, run_id, attempt_id, d, client, check_cancel):
        a = self.attempts(run_id)[attempt_id]
        for index in range(self.poll_count):
            try:
                check_cancel()
                result = client.poll(a['task_id'], endpoint=a.get('endpoint'))
                if result.status == 'SUCCEEDED':
                    quantity = result.usage.get('output_video_duration', result.usage.get('duration')) if isinstance(result.usage, dict) else None
                    if not isinstance(quantity, (int, float)) or isinstance(quantity, bool) or not math.isfinite(quantity) or quantity < 0:
                        quantity = None
                    rate = d['estimate']['amount'] / d['duration']
                    row = next(r for r in self.jobs.ledger.entries(run_id) if r.call_id == attempt_id)
                    if row.usage_status != 'known':
                        self.jobs.ledger.settle_media_call(run_id, attempt_id, quantity=quantity, ok=True,
                            estimated_cny=round(rate * quantity, 4) if quantity is not None else None,
                            request_id=result.task_id, pricing_source=d['estimate']['source'], note='百炼任务查询回执；估算不是账单。')
                    self.status(run_id, attempt_id, status='downloading', message='视频生成完成，正在取回并校验文件。')
                    raw = client.download(result.video_url, max_bytes=64 * 1024 * 1024)
                    validate_video(raw)
                    self.save_output(run_id, attempt_id, raw, '.mp4')
                    self.status(run_id, attempt_id, status='succeeded',
                        message='视频已保存，待观看验收。' + ('费用请在百炼平台查看。' if quantity is None else ''))
                    return
                if result.status in {'FAILED', 'CANCELED', 'UNKNOWN'}:
                    # A failed task is not proof of zero usage. Keep it explicit.
                    self.status(run_id, attempt_id, status='failed', message='百炼任务未完成；可检查输入后再发起新任务。')
                    return
                if index == 0:
                    self.status(run_id, attempt_id, status='submitted', message='百炼正在处理，等待视频完成。')
                if index + 1 < self.poll_count:
                    for _ in range(max(1, int(self.poll_delay * 5))):
                        check_cancel()
                        time.sleep(self.poll_delay / max(1, int(self.poll_delay * 5)))
            except JobCancelled:
                self.status(run_id, attempt_id, status='submitted', message='已停止本地等待，百炼任务可能继续并计费；可查询原任务。')
                return
            except Exception:
                self.status(run_id, attempt_id, status='retrieve_failed', message='暂未取回完整结果。已保存百炼任务，可查询原任务，不会重复生成。')
                return
        self.status(run_id, attempt_id, status='submitted', message='百炼仍在处理，稍后查询原任务即可。')

    def submit_image(self, run_id, attempt_id, d, raw, client, check_cancel, model, authorized):
        from .agents.codex_image import ImageRequest
        from .agents.codex_client import CodexUnavailable
        try:
            client.check_cancel = check_cancel
            with tempfile.TemporaryDirectory(prefix='studio-image-input-') as directory:
                root = Path(directory)
                refs = ()
                paths = []
                for index, (reference, data) in enumerate(zip(d['references'], raw), 1):
                    suffix = Path(reference['name']).suffix
                    path = root / f'reference-{index:02d}-{reference["purpose"]}{suffix}'
                    path.write_bytes(data)
                    paths.append(path)
                refs = tuple(paths)
                # The exact set must still be current at the provider boundary,
                # including revisions to later shots during this batch.
                self.validate_submission_authorization(run_id, attempt_id, authorized)
                result = client.generate(ImageRequest(prompt=d['prompt'], reference_paths=refs,
                    reference_root=root, output_dir=root / 'output', model=model))
                no_image_call = (result.provider_invoked and result.status == 'failed'
                                 and result.observed_image_calls == 0)
                if not result.provider_invoked or no_image_call:
                    self.jobs.ledger.settle_media_call(run_id, attempt_id, quantity=0, ok=False,
                        note=('Codex 文字轮已完整结束，没有调用图片工具。'
                              if no_image_call else 'Codex 在发送前停止，没有发起模型请求。'))
                else:
                    self.jobs.ledger.settle_media_call(run_id, attempt_id, quantity=None, ok=result.status == 'completed',
                        request_id=result.turn_id, note='Codex 图片事件未提供计费用量；文字 Tokens 单独保留。',
                        input_tokens=result.usage.input_tokens, output_tokens=result.usage.output_tokens, actual_model=result.model)
                self.status(run_id, attempt_id, observed_image_calls=result.observed_image_calls,
                    actual_model=result.model, provider_thread_id=result.thread_id, provider_turn_id=result.turn_id,
                    text_input_tokens=result.usage.input_tokens, text_output_tokens=result.usage.output_tokens,
                    provider_outcome=result.status, failure_code=result.failure_code)
                if result.images:
                    image = result.images[0]
                    self.save_output(run_id, attempt_id, image.path.read_bytes(), '.png' if image.mime == 'image/png' else '.webp' if image.mime == 'image/webp' else '.jpg')
                if result.status == 'completed' and len(result.images) == 1:
                    self.status(run_id, attempt_id, status='succeeded',
                        message='图片已保存，等待你的图审。')
                elif no_image_call:
                    self.status(run_id, attempt_id, status='failed',
                        message='Codex 已结束这轮文字回复，但没有调用图片工具；没有生成图片，可修改输入后重新提交。')
                else:
                    self.status(run_id, attempt_id, status='unknown' if result.provider_invoked else 'failed',
                        message='图片任务未完整结束，已保留可验证的结果，没有自动重试。'
                                if result.provider_invoked else '图片连接在调用前停止，没有提交模型请求。')
        except PipelineError:
            raise
        except CodexUnavailable:
            self.jobs.ledger.settle_media_call(run_id, attempt_id, quantity=0, ok=False,
                note='Codex 本机预检未通过，尚未发起模型请求。')
            self.status(run_id, attempt_id, status='failed', message='图片连接预检未通过，没有发起模型请求。请检查本机 Codex。')
        except Exception as exc:
            # Class name only, for the same reason as the video path above.
            self.status(run_id, attempt_id, status='unknown',
                        message=f'图片任务未完整返回，调用状态待核实，没有自动重试。（{type(exc).__name__}）')

    def prepare_refresh(self, run_id, attempt_id):
        a = self.attempts(run_id).get(attempt_id)
        if not a or a['media_kind'] != 'video' or not a.get('task_id'):
            raise ValueError('没有可查询的百炼任务，请先核实原提交结果。')
        d = self.get_draft(run_id, a['draft_id'])
        client = self.video_client()
        def run(_text, emit, check_cancel):
            with self.jobs.ledger.call_guard():
                self.poll_video(run_id, attempt_id, d, client, check_cancel)
                attempt = self.attempts(run_id)[attempt_id]
            return outcome(attempt, '原视频任务查询完成，没有提交新的生成请求。')
        return run, {'provider': 'dashscope', 'task_id': a['task_id'], 'new_generation': False}


